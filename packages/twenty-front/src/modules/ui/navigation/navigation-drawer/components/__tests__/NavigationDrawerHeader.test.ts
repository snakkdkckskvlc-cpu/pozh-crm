// пожсервис: замок на тупик «свернул меню — открыть негде».
//
// ЧТО БЫЛО. Кнопка сворачивания панели рисовалась ТОЛЬКО пока панель развёрнута.
// Обратную кнопку («развернуть») рисовала не сама панель, а соседняя шапка
// страницы (PageHeader) — отдельный компонент, который есть НЕ НА КАЖДОЙ
// странице. Двадцать один наш экран службы документов (`/documents/*`,
// `PozhScreenPage`) — простая страница без этой шапки.
//
// Свернул панель на такой странице — кнопки «развернуть» не было НИГДЕ на
// экране, а состояние «свёрнуто» запоминается в браузере и переживает
// перезагрузку страницы: тупик без выхода. Найдено живым обходом («кнопка
// закрывает меню, а открыть невозможно»); проверено в браузере до и после:
// на `/documents/legal` кнопка «развернуть» появилась ровно там, где раньше её
// не было.
//
// ПОЧЕМУ ПРОВЕРКА ЧИТАЕТ ИСХОДНИК, А НЕ РИСУЕТ КОМПОНЕНТ. Полный показ этого
// компонента тянет за собой панель рабочего пространства, GraphQL и переводы —
// тяжёлая обвязка ради одной строки условия. Здесь тот же приём, что и в
// `pozh-adresa.spec.ts` на стороне службы: замок на текст условия, которое уже
// один раз молча сломало вход в программу.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const исходник = readFileSync(
  join(__dirname, '..', 'NavigationDrawerHeader.tsx'),
  'utf-8',
);

describe('кнопка свернуть/развернуть панель', () => {
  it('файл вообще нашёлся и не пуст', () => {
    // Без этого проверка молча проходила бы на пустой строке.
    expect(исходник.length).toBeGreaterThan(500);
  });

  it('рисуется независимо от того, развёрнута панель или нет', () => {
    // Раньше здесь стояло `isNavigationDrawerExpanded && showCollapseButton` —
    // кнопка исчезала ровно тогда, когда она нужнее всего: чтобы открыть
    // свёрнутую панель обратно.
    expect(исходник).not.toMatch(
      /isNavigationDrawerExpanded\s*&&\s*showCollapseButton/,
    );
    expect(исходник).toMatch(/\{showCollapseButton\s*&&/);
  });

  it('меняет направление стрелки по состоянию, а не всегда «свернуть»', () => {
    // Кнопка одна и та же в обоих состояниях — значит она обязана понимать,
    // какую стрелку показать. Без этого «свёрнутая» кнопка звала бы свернуть
    // ещё раз вместо того, чтобы развернуть.
    expect(исходник).toMatch(
      /direction=\{isNavigationDrawerExpanded \? 'left' : 'right'\}/,
    );
  });
});
