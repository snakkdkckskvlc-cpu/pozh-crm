/**
 * Запрет выхода в интернет подключён во ВСЕХ точках входа, а не только в
 * главной.
 *
 * ЗАЧЕМ ЭТА ПРОВЕРКА ОТДЕЛЬНО ОТ ПРЕДЫДУЩЕЙ. Соседняя проверка
 * (pozh-netguard.spec.ts) убеждается, что запрет правильно решает, кого пускать.
 * Но правильный запрет, забытый в одном из процессов, не защищает ничего: до
 * 13.08.2026 он стоял только в сервере, а все почасовые задания — поход в реестр
 * программ раз в час, проверка обновлений, проверка платного ключа — крутятся в
 * ДРУГОМ процессе, где запрета не было. Половина обращений наружу уходила мимо.
 *
 * ПОЧЕМУ ПРОВЕРЯЕМ ЧТЕНИЕМ ФАЙЛА, А НЕ ЗАПУСКОМ. Запустить рабочий процесс в
 * проверке нельзя: ему нужны база, очередь и настройки. А вопрос, на который
 * надо ответить, — «стоит ли строка на месте», и он решается чтением. Тем же
 * приёмом ловят забытые правила в других проектах.
 *
 * ЧТО ЭТА ПРОВЕРКА ЛОВИТ. Три беды: точку входа забыли; подключение переехало
 * вниз и стало бесполезным; в Twenty появился новый отдельный процесс, о котором
 * никто не подумал (последние две проверки обходят исходники и команды запуска
 * сами и падают на незнакомой точке входа).
 */

import fs from 'node:fs';
import path from 'node:path';

const КОРЕНЬ_ПАКЕТА = path.resolve(__dirname, '..', '..');
const ПОДКЛЮЧЕНИЕ = "import 'src/pozh-netguard-install';";

/** Все процессы форка. Путь — от корня packages/twenty-server. */
const ТОЧКИ_ВХОДА: [файл: string, чтоЗапускает: string][] = [
  ['src/main.ts', 'сервер'],
  ['src/queue-worker/queue-worker.ts', 'фоновые задания'],
  ['src/command/command.ts', 'команды, переносы базы и установка приложений'],
  ['src/database/scripts/setup-db.ts', 'заведение базы'],
  ['src/database/scripts/truncate-db.ts', 'очистка базы'],
  [
    'src/database/clickHouse/migrations/run-migrations.ts',
    'переносы ClickHouse',
  ],
  ['src/database/clickHouse/seeds/run-seeds.ts', 'наполнение ClickHouse'],
];

const прочитать = (файл: string): string =>
  fs.readFileSync(path.join(КОРЕНЬ_ПАКЕТА, файл), 'utf8');

/** Номера строк, которыми файл что-то загружает: и import, и require. */
const строкиЗагрузки = (текст: string): [номер: number, строка: string][] =>
  текст
    .split('\n')
    .map((строка, номер): [number, string] => [номер, строка.trim()])
    .filter(
      ([, строка]) => /^import\b/.test(строка) || /\brequire\s*\(/.test(строка),
    );

describe('запрет сети подключён во всех точках входа', () => {
  describe('подключение стоит первой строкой загрузки', () => {
    it.each(ТОЧКИ_ВХОДА)('%s — %s', (файл) => {
      const первая = строкиЗагрузки(прочитать(файл))[0];

      // Комментарии и заголовки выше не мешают: они ничего не загружают.
      // Важно, чтобы РАНЬШЕ запрета не загружался никто.
      expect(первая?.[1]).toBe(ПОДКЛЮЧЕНИЕ);
    });
  });

  it('запрет не ставится вызовом функции: так он встаёт слишком поздно', () => {
    // Прежний вид правки — строка import с «установитьЗапретСети» и вызов под
    // ней — выглядит верно, но не работает: сборщик поднимает ВСЕ строки import
    // выше любого вызова, и подмена случается уже после загрузки Sentry и всего
    // остова приложения. Проверено на собранном файле dist/queue-worker/
    // queue-worker.js: вызов стоял последней строкой, после семи загрузок.
    for (const [файл] of ТОЧКИ_ВХОДА) {
      expect(прочитать(файл)).not.toContain('установитьЗапретСети(');
    }
  });

  it('в фоновых заданиях запрет загружается раньше Sentry и модуля заданий', () => {
    const загрузки = строкиЗагрузки(
      прочитать('src/queue-worker/queue-worker.ts'),
    ).map(([, строка]) => строка);

    const номерЗапрета = загрузки.findIndex((с) => с === ПОДКЛЮЧЕНИЕ);
    const номерSentry = загрузки.findIndex((с) => с.includes('src/instrument'));
    const номерЗаданий = загрузки.findIndex((с) =>
      с.includes('queue-worker.module'),
    );

    expect(номерЗапрета).toBe(0);
    expect(номерSentry).toBeGreaterThan(номерЗапрета);
    expect(номерЗаданий).toBeGreaterThan(номерЗапрета);
  });

  it('подключаемый файл действительно включает запрет', () => {
    // Иначе подключение — пустышка, и все проверки выше ничего не значат.
    const текст = прочитать('src/pozh-netguard-install.ts');

    expect(текст).toContain("from 'src/pozh-netguard'");
    expect(текст).toMatch(/^установитьЗапретСети\(\);$/m);
  });

  it('ни одна точка входа не забыта: сплошной обход исходников', () => {
    // Точка входа узнаётся по тому, что она поднимает приложение. Если в Twenty
    // появится новая — проверка упадёт здесь, а не тихо выпустит её в интернет.
    const найденные: string[] = [];
    const обойти = (папка: string): void => {
      for (const запись of fs.readdirSync(папка, { withFileTypes: true })) {
        const полный = path.join(папка, запись.name);

        if (запись.isDirectory()) {
          обойти(полный);
          continue;
        }
        if (!запись.name.endsWith('.ts') || запись.name.endsWith('.spec.ts')) {
          continue;
        }
        if (
          /\b(NestFactory|CommandFactory)\s*\./.test(
            fs.readFileSync(полный, 'utf8'),
          )
        ) {
          найденные.push(path.relative(КОРЕНЬ_ПАКЕТА, полный));
        }
      }
    };

    обойти(path.join(КОРЕНЬ_ПАКЕТА, 'src'));

    const известные = ТОЧКИ_ВХОДА.map(([файл]) => файл);

    expect(найденные.filter((файл) => !известные.includes(файл))).toEqual([]);
  });

  it('ни одна точка входа не забыта: сверка с командами запуска', () => {
    // Второй способ узнать точку входа — посмотреть, что запускают отдельным
    // процессом. Ловит случай, когда новый процесс завели командой, а кода
    // приложения в нём почти нет.
    const скрипты = [
      прочитать('package.json'),
      прочитать('project.json'),
      ...fs
        .readdirSync(path.join(КОРЕНЬ_ПАКЕТА, 'scripts'))
        .filter((имя) => имя.endsWith('.sh'))
        .map((имя) => прочитать(path.join('scripts', имя))),
    ].join('\n');

    const запускаемые = new Set<string>();

    // «node dist/queue-worker/queue-worker» → src/queue-worker/queue-worker.ts
    for (const [, путь] of скрипты.matchAll(/node\s+(dist\/[\w./-]+)/g)) {
      запускаемые.add(
        `src/${путь.replace(/^dist\//, '').replace(/\.js$/, '')}.ts`,
      );
    }
    // «nest start --entryFile queue-worker/queue-worker»
    for (const [, путь] of скрипты.matchAll(/--entryFile\s+([\w./-]+)/g)) {
      запускаемые.add(`src/${путь.replace(/\.js$/, '')}.ts`);
    }
    // «ts-node -- src/database/clickHouse/migrations/run-migrations.ts»
    for (const [путь] of скрипты.matchAll(/src\/[\w./-]+\.ts\b/g)) {
      запускаемые.add(путь);
    }

    const известные = ТОЧКИ_ВХОДА.map(([файл]) => файл);
    const забытые = [...запускаемые].filter(
      (файл) =>
        !известные.includes(файл) &&
        fs.existsSync(path.join(КОРЕНЬ_ПАКЕТА, файл)),
    );

    expect(забытые).toEqual([]);
  });
});
