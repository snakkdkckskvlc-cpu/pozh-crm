// пожсервис: замок на ошибку, которая в этом проекте повторилась трижды.
//
// Кириллица в АДРЕСЕ ручки не работает и ломается молча. Уже было:
//   1) имя параметра `пропуск` — uvicorn отвечал «Invalid HTTP request»;
//   2) кириллический путь в клиенте на Python — падение при кодировании;
//   3) `@Get('экраны')` здесь — маршрут значился в списке, а запрос получал 404,
//      потому что Nest сверяет адрес ДО раскодирования, а браузер кодирует всегда.
//
// Третий случай прожил дольше всех: ручка не работала ни разу, и заметить это
// удалось только сквозным прогоном. Поэтому проверка читает исходники с диска, а
// не сверяется с рукописным списком: рукописный устаревает молча, ровно как та
// ручка.
//
// Русский остаётся везде, где его видит человек: названия экранов, тексты
// ошибок, имена функций и переменных. Запрет только на адрес.

import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ПАПКА = join(__dirname, '..');

const исходники = (): string[] =>
  readdirSync(ПАПКА)
    .filter((имя) => имя.endsWith('.ts'))
    .map((имя) => join(ПАПКА, имя));

// Достаёт адрес из @Controller('...'), @Get('...'), @Post('...') и остальных.
const АДРЕСА = /@(?:Controller|Get|Post|Put|Patch|Delete|All)\(\s*'([^']*)'/g;

describe('адреса ручек ПожСервиса', () => {
  it('файлы модуля вообще нашлись', () => {
    // Без этого вся проверка молча проходила бы на пустом списке — та же
    // болезнь, от которой она и заведена.
    expect(исходники().length).toBeGreaterThan(0);
  });

  it('не содержат ни одной буквы вне латиницы', () => {
    const плохие: string[] = [];

    for (const файл of исходники()) {
      // Комментарии выбрасываются, иначе проверка ловит объяснение ошибки как
      // саму ошибку: рядом с каждой правкой здесь написано, что было не так, и
      // неправильный адрес приведён примером. Так и вышло с первого прогона.
      const текст = readFileSync(файл, 'utf-8')
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .replace(/\/\/.*$/gm, '');

      for (const совпадение of текст.matchAll(АДРЕСА)) {
        const адрес = совпадение[1];

        // eslint-disable-next-line no-control-regex
        if (/[^\x00-\x7F]/.test(адрес)) {
          плохие.push(`${файл.split('/').pop()}: «${адрес}»`);
        }
      }
    }

    expect(плохие).toEqual([]);
  });

  it('список экранов не хранится копией, а спрашивается у службы', () => {
    // Копия здесь была и называлась «вторым замком». Она им не была: файлы с
    // диска отдаёт только служба. Копия могла лишь разойтись с оригиналом —
    // пункт меню без экрана или экран без пункта.
    const текст = readFileSync(join(ПАПКА, 'pozh-embed.controller.ts'), 'utf-8');

    expect(текст).toContain('/встроенный/список');
    expect(текст).not.toMatch(/const РАЗРЕШЁННЫЕ/);
  });
});
