//
// В старой программе это решено тем, что такие поля не отдаются в списковых
// ответах вовсе. В Twenty так не сделать — здесь права, и решается это ролью.
//
// ДВЕ РОЛИ, А НЕ ОДНА С ОГОВОРКАМИ:
//
//   «Сотрудник»    — вся обычная работа: контрагенты, договоры, транспорт,
//                    листы, огнетушители, сроки. Персональных данных водителя
//                    не видит вовсе — ни прочитать, ни поправить.
//   «Кадры»        — то же плюс персональные данные. Её выдают поимённо.
//
// Почему запрет на весь объект, а не на отдельные поля: у объекта есть
// заголовок записи, и его правами не спрячешь. Поэтому весь объект целиком, а
// заголовком у него нарочно поставлена подпись без фамилии — «Документы
// водителя №…».
//
// ЧЕГО ЭТИ РОЛИ НЕ ДЕЛАЮТ. Они не делят записи между людьми: любой сотрудник
// видит всех контрагентов и все листы. В компании тридцать человек и одна общая
// работа — делить их незачем, а лишние перегородки люди обходят просьбами
// «посмотри у себя».

