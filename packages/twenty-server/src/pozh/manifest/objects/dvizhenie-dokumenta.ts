// пожсервис: объект «Движение документа» — журнал прохождения бумаг по людям и
// этапам.
//
// Разбор с полями и почему они такие — docs/russian-business/SCHEMA_PLAN.md, §12.
// Про сумму — «Решение 1».
//
// ПОЧЕМУ ЭТОТ ОБЪЕКТ ГЛАВНЫЙ, ХОТЯ В ПЛАНЕ СТОИТ ПОСЛЕДНИМ.
//
// Все остальные объекты отвечают на вопрос «что у нас есть»: какие машины, какие
// огнетушители, какие договоры. Этот — единственный, который отвечает на вопрос
// «как мы работаем». Он же единственный измерительный прибор компании: пока
// движения документов не записываются, фраза «счета вечно застревают» остаётся
// ощущением, которое нечем ни подтвердить, ни опровергнуть. С этой таблицей она
// становится числом: у кого лежат, по сколько, какие виды документов застревают
// чаще.
//
// Отсюда два следствия для схемы:
//
// 1. «У кого лежит» и «Состояние» важнее всего остального в объекте. Сумма и
//    предмет — справочные, а эта пара и есть измерение.
// 2. Записи не редактируются задним числом «чтобы было красиво». Испорченное
//    измерение хуже отсутствующего: по нему принимают решения.
//
// ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ. Разрешённые переходы между состояниями схемой
// не выражаются: список выбора не знает, что из «закрыт» никуда нельзя. Переходы
// стережёт процесс или служба документов, схема хранит только текущее состояние.

import { type ObjectFieldManifest, type ObjectManifest } from 'twenty-shared/application';
import { type FieldMetadataType } from 'twenty-shared/types';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import {
  выбор,
  дата,
  датаВремя,
  деньги,
  источник,
  опознаватель,
  текст,
  число,
} from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.движениеДокумента;

// Виды документов. По ним считается итог месяца, поэтому список не украшение:
// итог складывается по актам, а не по всем документам подряд, — иначе счёт и
// закрывающий его акт удвоят месяц.
//
// Значения списка выбора Twenty требует ЗАГЛАВНЫМИ с подчёркиваниями, человек
// видит подпись. Значения из списка можно добавлять, но нельзя удалять: при
// перестройке списка записи с исчезнувшим значением теряют его молча (правило 9).
const видыДокумента = [
  { value: 'INVOICE', label: 'Счёт', color: 'sky' },
  { value: 'ACT', label: 'Акт', color: 'green' },
  { value: 'CONTRACT', label: 'Договор', color: 'purple' },
  { value: 'LETTER', label: 'Письмо', color: 'gray' },
];

const состоянияДокумента = [
  { value: 'IN_PROGRESS', label: 'В работе', color: 'yellow' },
  { value: 'APPROVED', label: 'Завизирован', color: 'green' },
  { value: 'REJECTED', label: 'Отклонён', color: 'red' },
  { value: 'CLOSED', label: 'Закрыт', color: 'gray' },
];

export const движениеДокумента: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhDocumentMovement',
  namePlural: 'pozhDocumentMovements',
  labelSingular: 'Движение документа',
  labelPlural: 'Движение документов',
  description: 'Журнал прохождения документов: вид, состояние, у кого лежит, сколько рабочих часов в работе.',
  icon: 'IconRoute',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'number'),
  fields: [
    // Уникальность НЕ ставим, и это разбор, а не недосмотр: у счёта и акта
    // нумерация своя, номер «14» встречается у каждого вида, да ещё и каждый год
    // заново. Запрет повторов не дал бы завести акт № 14 после счёта № 14.
    //
    // Обязательность тоже не ставим на уровне базы: пометка «правило» в плане
    // означает, что заполненность держит служба документов и форма ввода, а база
    // допускает пусто. Поставить сюда пустую строку по умолчанию было бы
    // самообманом: запись с пустым номером прошла бы как заполненная.
    текст({
      объект: О,
      имя: 'number',
      подпись: 'Номер документа',
      пояснение: 'Как записан на самом документе. Повторы допускаются: у разных видов нумерация своя.',
    }),
    // Русская подпись — «Вид документа», латинское имя другое: и `type`, и
    // `event` входят в 63 запрещённых имени Twenty, выкладка с ними не проходит.
    //
    // Значение по умолчанию — «Счёт», первый вариант из плана: план требует,
    // чтобы вид не был пустым, но какой подставлять, не называет. ОСТОРОЖНО:
    // именно по этому полю считается итог месяца, значит документ, у которого
    // вид забыли выбрать, молча посчитается счётом. Служба документов обязана
    // ставить вид явно и никогда не полагаться на умолчание.
    выбор({
      объект: О,
      имя: 'kind',
      подпись: 'Вид документа',
      пояснение: 'По этому полю считается итог месяца: складываются акты, а не все документы подряд.',
      варианты: видыДокумента,
      поумолчанию: 'INVOICE',
    }),
    текст({
      объект: О,
      имя: 'subject',
      подпись: 'Предмет',
      пояснение: 'За что документ: обслуживание за март, перезарядка, монтаж.',
    }),
    // ДЕНЬГИ — те же правила, что у суммы договора, и по той же причине.
    //
    // Хранение: тип «Деньги» — единственный точный в Twenty. Обычное «Число»
    // становится колонкой с плавающей запятой и теряет копейки, точный тип
    // NUMERIC руками создать не дают. Единица хранения — микро-рубль, одна
    // миллионная рубля; копейка = 10 000 микро-рублей.
    //
    // Сумму кладёт служба документов ГОТОВЫМ ЦЕЛЫМ ЧИСЛОМ микро-рублей: ввод с
    // экрана умножает набранное на миллион дробной арифметикой и теряет доли
    // копейки. Здесь это опаснее, чем у договора: суммы документов складываются
    // в итог месяца, и потери копятся.
    //
    // Три настройки поверх помощника `деньги`, которых он сам не ставит:
    // 1. `isUIEditable: false` — только чтение на экране. Защита от случайности,
    //    не запрет: признак работает в браузере, на сервере проверки нет.
    //    Настоящий запрет ставится правом роли на поле.
    // 2. `universalSettings` — показ «полностью» и два знака. По умолчанию
    //    Twenty показал бы «1,2k» вместо «1 234,56 ₽».
    // 3. `defaultValue` с кодом валюты — рубль: сумма без единицы измерения
    //    ничего не значит.
    //
    // Приписка «как денежное» (`as`) нужна проверке типов, а не базе: помощник
    // возвращает «поле какого-нибудь вида», и к такому описанию нельзя дописать
    // настройки, которые есть только у денег. Сужаем до денежного — и дописываем.
    {
      ...(деньги({
        объект: О,
        имя: 'amount',
        подпись: 'Сумма документа',
        пояснение: 'Кладёт служба документов целым числом микро-рублей. С экрана не правится.',
      }) as ObjectFieldManifest<FieldMetadataType.CURRENCY>),
      isUIEditable: false,
      universalSettings: { format: 'full', decimals: 2 },
      defaultValue: { amountMicros: null, currencyCode: "'RUB'" },
    },
    // Половина измерения: на каком этапе документ сейчас. Вторая половина — «У
    // кого лежит». Значение по умолчанию «в работе» прямо названо в плане: любой
    // только что заведённый документ уже в работе, других состояний у него быть
    // не может.
    //
    // Ещё раз про то, чего схема не умеет: она не запретит переход из «закрыт» в
    // «в работе». Это стережёт процесс, а не список выбора.
    выбор({
      объект: О,
      имя: 'state',
      подпись: 'Состояние',
      пояснение: 'Этап прохождения. Разрешённые переходы стережёт служба, а не база.',
      варианты: состоянияДокумента,
      поумолчанию: 'IN_PROGRESS',
    }),
    дата({
      объект: О,
      имя: 'dueOn',
      подпись: 'Срок',
      пояснение: 'К какому числу документ должен быть закрыт. По этому полю-дате работает правило срока.',
    }),
    // Дата СО ВРЕМЕНЕМ, а не просто дата, — без часа и минуты нечего считать:
    // «отдан в пятницу, закрыт в понедельник» и «отдан в пятницу в 17:00, закрыт
    // в понедельник в 9:00» — это разные числа рабочих часов.
    датаВремя({
      объект: О,
      имя: 'closedAt',
      подпись: 'Когда закрыт',
      пояснение: 'Точный момент закрытия. Со временем, иначе рабочие часы не посчитать.',
    }),
    // ТОТ САМЫЙ ИЗМЕРИТЕЛЬ.
    //
    // Часы РАБОЧИЕ, а не календарные: Пн–Пт, 8:30–17:30, час обеда. Разница не
    // косметическая — счёт, отданный в пятницу в 17:00 и завизированный в
    // понедельник в 9:00, по календарю пролежал 64 часа, а по работе — полтора.
    // Первое число показывает несуществующую беду и заставляет «разбираться»
    // там, где всё в порядке.
    //
    // Почему обычное число, а не «длительность»: типа «длительность/интервал» в
    // Twenty нет вовсе — 23 типа полей, интервала среди них нет. Считает часы
    // служба документов, поле только хранит результат; поэтому оно и не
    // обязательное — у документа в работе итога ещё нет.
    число({
      объект: О,
      имя: 'workingHours',
      подпись: 'Рабочих часов в работе',
      пояснение: 'Считает служба документов. Часы рабочие (Пн–Пт, 8:30–17:30, минус обед), а не календарные.',
    }),
    // ЗДЕСЬ ЖЕ ДОЛЖНЫ БЫТЬ ДВЕ ССЫЛКИ, обе к чужим объектам, поэтому их сводят
    // отдельно (перечислены в отчёте):
    //
    // «Контрагент» → Контрагент, при удалении «запретить»: по кому документ —
    //   написано в сданном счёте, задним числом это не меняется.
    // «У кого лежит» → сотрудник Twenty, при удалении «обнулить»: человек
    //   уволился — движения документов должны остаться, иначе измерение
    //   пропадает вместе с ним. Имя `holder`, а не `user`: `user` запрещён.
    ...источник(О),
  ],
};
