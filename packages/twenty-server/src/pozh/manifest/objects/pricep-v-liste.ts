// пожсервис: объект «Прицеп в путевом листе» — строчка-связка между листом и
// прицепом.
//
// ЗАЧЕМ ОН ВООБЩЕ НУЖЕН. К одному листу может относиться несколько прицепов, и
// один прицеп за месяц попадает в разные листы. Связи «многие-ко-многим» в
// Twenty как вида не существует — видов ровно два, «многие-к-одному» и
// «один-ко-многим». Штатный способ выразить «много к многим» — третий объект,
// в котором одна запись означает «этот прицеп был в этом листе».
//
// ЧТО УВИДИТ СЕКРЕТАРЬ. Красивый показ связанных записей вместо промежуточных
// строчек включается отдельным признаком (`IS_JUNCTION_RELATIONS_ENABLED`) и
// помечен у Twenty как бета. Без него в карточке листа будут видны сами
// строчки-связки. Это вопрос удобства, не данных, но посмотреть на тестовой
// установке надо до обучения людей.
//
// Разбор с полями — docs/russian-business/SCHEMA_PLAN.md, §8а.

import { type ObjectManifest } from 'twenty-shared/application';
import { RelationOnDeleteAction } from 'twenty-shared/types';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { опознаватель, связь, текст, число } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.прицепВЛисте;

/**
 * Связь «строчка → путевой лист». Половину-список забирает `putevoj-list.ts`.
 *
 * ЕДИНСТВЕННОЕ МЕСТО ВО ВСЕЙ СХЕМЕ, ГДЕ УМЕСТНО «ПО ЦЕПОЧКЕ» (CASCADE).
 * Строчка «прицеп в путевом листе» без листа не значит ничего: это не запись о
 * прицепе (прицеп живёт в своём справочнике) и не запись о работе, а только
 * отметка «этот прицеп был в этом листе». Останься она без листа — получим
 * мусор, который никто никогда не найдёт и не удалит.
 *
 * И оговорка, снимающая испуг: сами путевые листы не удаляются вообще —
 * удаление у них выключено для всех ролей, ошибочный лист аннулируется. То есть
 * «по цепочке» здесь срабатывает практически только при сносе объекта целиком.
 */
export const связьСтрочкиСЛистом = связь({
  откуда: О,
  куда: ОБЪЕКТЫ.путевойЛист,
  имяСсылки: 'waybill',
  подписьСсылки: 'Путевой лист',
  имяСписка: 'trailerRows',
  подписьСписка: 'Прицепы',
  приУдалении: RelationOnDeleteAction.CASCADE,
  пояснение: 'В каком листе записан прицеп.',
});

