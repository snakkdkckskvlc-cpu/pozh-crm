// ЧЕГО ЗДЕСЬ ПОКА НЕ ХВАТАЕТ И ПОЧЕМУ ЭТО ВАЖНО.
//
// По плану на пару «лист + прицеп» нужен составной уникальный указатель — он
// держит от того, чтобы один прицеп попал в один лист дважды. Описать его
// сейчас нельзя: половина пары (ссылка на прицеп) в этом файле отсутствует, а
// указатель на одну лишь ссылку на лист означал бы «в листе не больше одного
// прицепа», то есть прямо противоположное нужному.
//
// Указатель заводится в `pozh-manifest.ts`, в поле `indexes`, СРАЗУ ПОСЛЕ того
// как в этот объект добавят ссылку на прицеп: `isUnique: true`, поля —
// ссылка на лист и ссылка на прицеп. Обе ссылки «многие-к-одному», такие в
// уникальный указатель включать можно.
