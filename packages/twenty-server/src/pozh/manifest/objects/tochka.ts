// пожсервис: объект «Точка» — справочник мест, куда ездят машины.
//
// Разбор с полями и почему они такие — docs/russian-business/SCHEMA_PLAN.md, §6.

import { type ObjectManifest } from 'twenty-shared/application';

import { кудаРейса, откудаРейса } from 'src/pozh/manifest/objects/svyazi-transporta';
import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { источник, опознаватель, текст, флажок, число } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.точка;

export const точка: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhPoint',
  namePlural: 'pozhPoints',
  labelSingular: 'Точка',
  labelPlural: 'Точки',
  description: 'Места, между которыми ходят машины: база, объекты заказчиков, заправки.',
  icon: 'IconMapPin',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'name'),
  fields: [
    текст({
      объект: О,
      имя: 'name',
      подпись: 'Название',
      пояснение: 'Как точку называют в разговоре: «База», «Склад на Мира».',
      обязательно: true,
      уникально: true,
    }),
    // Латинское имя не `address`: это имя занято Twenty под собственный составной
    // тип, и поле с ним не заводится. Подпись на экране остаётся «Адрес».
    //
    // Готовый тип «Адрес» здесь не берём и по существу: он раскладывается на
    // восемь колонок чужого формата, российских «корпус» и «квартира» в нём нет,
    // а широта с долготой нужны нам отдельными полями — по ним считаются
    // расстояния.
    текст({
      объект: О,
      имя: 'addressLine',
      подпись: 'Адрес',
      пояснение: 'Одной строкой, как говорят водителю.',
    }),
    // Единственное место в схеме, где дробное число — это правильно: координата
    // и есть дробь, терять её знаки нельзя. Запрет на дробные касается денег и
    // накапливаемых величин, а не географии.
    число({
      объект: О,
      имя: 'latitude',
      подпись: 'Широта',
      пояснение: 'Дробное число — это координата, а не деньги.',
    }),
    число({
      объект: О,
      имя: 'longitude',
      подпись: 'Долгота',
      пояснение: 'Дробное число — это координата, а не деньги.',
    }),
    // Метры целым числом: расстояние идёт в расчёт нормы расхода, а там дробная
    // часть накапливалась бы от рейса к рейсу.
    число({
      объект: О,
      имя: 'distanceFromBaseM',
      подпись: 'Расстояние от базы, м',
      пояснение: 'Метры целым числом. 12,4 км — это 12400.',
    }),
    // Отмечена одна точка — наш гараж. Признак нужен расчёту: от базы считается
    // расстояние, и с неё начинается день.
    флажок({
      объект: О,
      имя: 'isBase',
      подпись: 'Это база',
      пояснение: 'Отмечен наш гараж — от него считается расстояние.',
    }),
    // Обратные половины связей с рейсом. Сами пары объявлены в
    // svyazi-transporta.ts: рейс ссылается на точку дважды, отсюда два разных
    // списка — «уехали отсюда» и «приехали сюда».
    откудаРейса.список,
    кудаРейса.список,
    ...источник(О),
  ],
};
