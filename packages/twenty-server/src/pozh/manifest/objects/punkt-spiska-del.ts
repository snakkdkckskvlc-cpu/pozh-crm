// пожсервис: пункт списка дел внутри задачи.
//
// ЗАЧЕМ. Обслуживание огнетушителя — это не «сделать», а пять операций подряд:
// осмотр корпуса, проверка давления, перезарядка, пломба, отметка в журнале.
// Сейчас это либо пять отдельных задач — и доска забита однотипными карточками,
// либо одна задача, в которой половину забыли.
//
// Это единственное, чего у задач Twenty нет вовсе, а нам нужно заметно: в
// YouGile такие списки называются подзадачами и показывают «сделано 3 из 7».
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ОБЪЕКТ, А НЕ ТЕКСТ В ОПИСАНИИ. Текстом нельзя ни отметить
// выполненное, ни посчитать остаток, ни спросить «что не доделано по этому
// объекту». А спрашивать будут именно так.
//
// ЧЕГО ЗДЕСЬ ПОКА НЕТ, И ЭТО НАДО ЗНАТЬ. На странице задачи Twenty показывает
// связанные записи узкой полоской ярлыков: пять шагов ужимаются в одну строку,
// отметок «сделано» и счёта «сделано 3 из 7» не видно. Пункты читаются, если
// открыть их списком, но работать прямо на задаче неудобно.
//
// Две попытки поправить это описанием не сработали, обе проверены глазами:
//   - свой вид страницы задачи ЗАМЕНИЛ стандартный целиком — пропали срок,
//     исполнитель, состояние, описание и обсуждение. Откачено сразу;
//   - вкладка к стандартной странице по её опознавателю выложилась «успешно»,
//     а на деле не создалась: у страницы остались только родные вкладки.
//     Молчаливый отказ, найден запросом, а не на глаз.
//
// Вывод: показ на странице задачи правится кодом внешней части, а не описанием.
// Это отдельная работа, и её цена честно не проверена.

