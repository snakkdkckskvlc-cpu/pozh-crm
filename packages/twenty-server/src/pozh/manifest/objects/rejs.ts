// пожсервис: объект «Рейс» — одна поездка машины: выехал, вернулся, сколько
// проехал и сколько сжёг.
//
// Разбор с полями и почему они такие — docs/russian-business/SCHEMA_PLAN.md, §7.
//
// ЧЕГО ЗДЕСЬ ПОКА НЕТ И ПОЧЕМУ. План даёт рейсу ещё две ссылки — на водителя и
// на путевой лист. Обе не описаны здесь намеренно: у связи две половины, вторая
// половина (обратный список) принадлежит водителю и путевому листу, а эти
// объекты описываю не я. Половина без второй половины не «частично работает» —
// она роняет всю выкладку, потому что ищется по опознавателю. Пары появятся
// одной строкой, когда оба объекта будут в описании; отмечено в отчёте.
//
// ЧЕГО СХЕМА НЕ ВЫРАЖАЕТ ВООБЩЕ. «Машина в рейсе не может уехать второй раз» —
// это правило «нет второй записи с этой машиной и пустым „Вернулся"». Частичного
// уникального признака в Twenty нет ни в каком виде, поэтому правило проверяет
// служба документов при записи. Проверка в коде обходится, признак базы — нет, и
// здесь мы вынужденно берём первое.

import { type ObjectManifest } from 'twenty-shared/application';

import { кудаРейса, машинаРейса, откудаРейса } from 'src/pozh/manifest/objects/svyazi-transporta';
import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import {
  выбор,
  датаВремя,
  источник,
  опознаватель,
  текст,
  число,
} from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.рейс;

export const рейс: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhTrip',
  namePlural: 'pozhTrips',
  labelSingular: 'Рейс',
  labelPlural: 'Рейсы',
  description: 'Поездка машины: откуда, куда, когда выехал и вернулся, пробег и топливо.',
  icon: 'IconRoute',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'label'),
  fields: [
    // Заголовок записи склеивает служба документов: позывной машины плюс дата
    // выезда. Отдельным полем, а не выражением, потому что заголовок в Twenty —
    // это одно конкретное поле; вычисляемых заголовков нет. Пустая строка по
    // умолчанию — чтобы новый рейс не выглядел в списке пустой строкой.
    текст({
      объект: О,
      имя: 'label',
      подпись: 'Метка',
      пояснение: 'Заголовок записи: позывной машины и дата выезда. Складывает служба документов.',
      обязательно: true,
      правитЧеловек: false,
    }),
    // Половины этих связей объявлены в svyazi-transporta.ts вместе с причиной,
    // почему при удалении выбрано «запретить» у машины и «обнулить» у точек.
    машинаРейса.ссылка,
    откудаРейса.ссылка,
    кудаРейса.ссылка,
    // Запасной адрес: половина поездок идёт по разовым адресам, заводить их в
    // справочник точек ради одного раза незачем. Латинское имя не `address` —
    // это имя занято Twenty; подпись на экране прежняя.
    текст({
      объект: О,
      имя: 'destinationAddressLine',
      подпись: 'Адрес назначения',
      пояснение: 'Заполняется, когда точки в справочнике нет и заводить её незачем.',
    }),
    текст({ объект: О, имя: 'purpose', подпись: 'Цель поездки' }),
    // «Выехал» в плане помечен обязательным по правилу, а не базой, и это
    // осознанно: обязательность в Twenty означает наличие значения по умолчанию,
    // а «время выезда по умолчанию» — выдумка, которая тихо проставится в каждый
    // недозаполненный рейс. Пусть лучше пусто, а проверяет служба документов.
    датаВремя({
      объект: О,
      имя: 'departedAt',
      подпись: 'Выехал',
      пояснение: 'Когда машина ушла с базы.',
    }),
    // Пустое «Вернулся» — это не пропуск, а состояние «машина сейчас в рейсе».
    // На нём же держится проверка «второй раз не уедет» в службе документов.
    датаВремя({
      объект: О,
      имя: 'returnedAt',
      подпись: 'Вернулся',
      пояснение: 'Пусто — значит машина ещё в рейсе.',
    }),
    // Метры и миллилитры целым числом — из них считается расход, и дробная часть
    // копилась бы от рейса к рейсу. Про предел разрядности у пробега — та же
    // оговорка, что и у машины: план просит «большое целое», помощник `число`
    // разрядность не задаёт (отмечено в отчёте).
    число({
      объект: О,
      имя: 'odometerAtDepartureM',
      подпись: 'Пробег на выезде, м',
      пояснение: 'Метры целым числом, показание одометра при выезде.',
    }),
    число({
      объект: О,
      имя: 'odometerAtReturnM',
      подпись: 'Пробег на возврате, м',
      пояснение: 'Метры целым числом, показание одометра при возврате.',
    }),
    число({
      объект: О,
      имя: 'fuelIssuedMl',
      подпись: 'Выдано топлива, мл',
      пояснение: 'Миллилитры целым числом. 45,5 л — это 45500.',
    }),
    // СНИМОК нормы, а не ссылка на машину. Приказ меняет норму задним числом, и
    // без снимка пересчёт закрытого месяца дал бы не те цифры, по которым уже
    // списали топливо. Пусто — значит утверждённой нормы на тот день не было, и в
    // бланке печатается прочерк.
    число({
      объект: О,
      имя: 'fuelRateHundredths',
      подпись: 'Норма расхода, сотые',
      пояснение: 'Снимок нормы машины на день рейса, а не ссылка на машину. Сотые доли литра.',
    }),
    // Отличает то, что человек отметил руками, от того, что приехало из
    // спутникового слежения: у трекерных записей другая точность времени, и при
    // разборе споров это первое, что спрашивают.
    выбор({
      объект: О,
      имя: 'recordSource',
      подпись: 'Источник записи',
      пояснение: 'Кто отметил рейс: человек или спутниковое слежение.',
      варианты: [
        { value: 'VRUCHNUYU', label: 'Вручную', color: 'blue' },
        { value: 'TREKER', label: 'Трекер', color: 'turquoise' },
      ],
      поумолчанию: 'VRUCHNUYU',
    }),
    // Номер строки в путевом листе. Само поле осмысленно и без ссылки на лист:
    // порядок строк переносится из старой базы вместе с рейсами.
    число({
      объект: О,
      имя: 'positionInWaybill',
      подпись: 'Порядковый номер в листе',
      пояснение: 'Какой строкой рейс идёт в путевом листе.',
    }),
    текст({ объект: О, имя: 'customerCode', подпись: 'Код заказчика' }),
    // Латинское имя не `user`: имя занято Twenty. Это не наш нынешний
    // пользователь, а фамилия из старой базы — кто завёл запись в Twenty,
    // записывается само, отдельного поля для этого не нужно.
    текст({
      объект: О,
      имя: 'legacyUserName',
      подпись: 'Пользователь',
      пояснение: 'Кто завёл запись в старой базе. В Twenty автор записи есть сам.',
    }),
    текст({ объект: О, имя: 'consignor', подпись: 'Грузоотправитель' }),
    ...источник(О),
  ],
};
