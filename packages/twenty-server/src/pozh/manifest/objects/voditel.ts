// пожсервис: объект «Водитель» — справочник водителей.
//
// ГЛАВНОЕ. СНИЛС, серии и номера удостоверений здесь НЕТ и быть не должно. Они
// лежат в отдельном объекте «Персональные данные водителя»
// (`dannye-voditelya.ts`). Причина в двух словах: запрет на поле в Twenty
// двоичный — кто видит поле в карточке, тот получит его же списком по всем
// водителям и выгрузкой в файл; разделения «в карточке да, в списке нет» в коде
// нет вовсе. Поэтому список водителей физически не содержит этих колонок — их
// неоткуда взять. Полный разбор — решение 3 плана схемы.
//
// ВОДИТЕЛЕЙ НЕ УДАЛЯЮТ. Удаление выключается правами на объект
// (`canSoftDeleteObjectRecords` и `canDestroyObjectRecords` в описании роли —
// `objectPermissions`), включая администратора: запрет на объекте перекрывает
// общее разрешение роли. Ушёл человек — снимаем признак «Активен». Иначе
// сданный путевой лист лишится обязательного реквизита. Права описываются в
// роли, а не здесь; в этом файле их выразить нечем.
//
// Разбор с полями — docs/russian-business/SCHEMA_PLAN.md, §3.

import { type ObjectManifest } from 'twenty-shared/application';

import { связьПерсональныхДанныхСВодителем } from 'src/pozh/manifest/objects/dannye-voditelya';
import { связьЛистаСВодителем } from 'src/pozh/manifest/objects/putevoj-list';
import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { источник, опознаватель, текст, флажок } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.водитель;

export const водитель: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhDriver',
  namePlural: 'pozhDrivers',
  labelSingular: 'Водитель',
  labelPlural: 'Водители',
  description:
    'Справочник водителей. Персональные данные вынесены в отдельный объект и в этот список не попадают.',
  icon: 'IconSteeringWheel',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'fullName'),
  fields: [
    // ФИО одной строкой. Готовый тип «ФИО» не берём: в нём только имя и
    // фамилия, отчества нет, а в путевом листе водитель пишется полностью.
    //
    // Пустым база его оставить позволяет, и это не недосмотр: «обязательное» в
    // Twenty означает лишь «есть значение по умолчанию», то есть запись с
    // пустой строкой всё равно прошла бы как заполненная. Настоящую
    // обязательность держит служба документов при записи.
    текст({
      объект: О,
      имя: 'fullName',
      подпись: 'ФИО',
      пояснение: 'Полностью, одной строкой — как пишется в путевом листе.',
    }),
    текст({
      объект: О,
      имя: 'personnelNumber',
      подпись: 'Табельный номер',
      пояснение:
        'Уникален: держит от двойного заведения одного человека. Он же попадает в метку '
        + 'персональных данных — «ПД-00123».',
      уникально: true,
    }),
    // Категорий у человека несколько (B, C, E). Для такого в Twenty есть тип
    // «список значений», но помощника для него в `pozh-pole.ts` пока нет, а
    // заводить поле мимо помощников в этом проекте нельзя. Пока текст, значения
    // через запятую. ЭТО НАДО ПОМЕНЯТЬ ДО ПЕРВОЙ ВЫКЛАДКИ: тип поля после
    // создания не меняется — только удалить поле вместе с данными и завести
    // заново.
    текст({
      объект: О,
      имя: 'licenseCategories',
      подпись: 'Категории',
      пояснение: 'B, C, E — через запятую. Временно текстом, нужен тип «список значений».',
    }),
    текст({
      объект: О,
      имя: 'tachographCard',
      подпись: 'Карточка водителя',
      пояснение: 'Номер карты тахографа.',
    }),
    // «Активен» вместо удаления — и по умолчанию «да», иначе каждый заведённый
    // водитель появлялся бы уволенным.
    флажок({
      объект: О,
      имя: 'isActive',
      подпись: 'Активен',
      пояснение: 'Снимается вместо удаления: выписанные листы должны сохранить водителя.',
      поумолчанию: true,
    }),
    // Обратные половины связей. Каждая связь описана в файле того объекта,
    // который на нас ссылается, и обе её половины обязаны попасть в описание
    // ровно по одному разу — забытая половина роняет всю выкладку.
    связьПерсональныхДанныхСВодителем.список,
    связьЛистаСВодителем.список,
    ...источник(О),
  ],
};
