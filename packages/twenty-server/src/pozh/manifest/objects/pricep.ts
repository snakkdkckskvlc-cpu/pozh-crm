// пожсервис: объект «Прицеп» — справочник прицепов, которые цепляются к машинам.
//
// Разбор с полями и почему они такие — docs/russian-business/SCHEMA_PLAN.md, §5.
//
// СВЯЗЕЙ У ПРИЦЕПА ЗДЕСЬ НЕТ, и это не забывчивость. К одному путевому листу
// относится несколько прицепов, а один прицеп попадает в разные листы; связи
// «многие-ко-многим» в Twenty как типа не существует, поэтому между ними стоит
// отдельный объект-связка «Прицеп в путевом листе» (§8а плана). Обе половины
// той связи принадлежат связке и путевому листу — их описывает тот, кто делает
// эти объекты.

import { type ObjectManifest } from 'twenty-shared/application';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { источник, опознаватель, текст, флажок } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.прицеп;

export const прицеп: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhTrailer',
  namePlural: 'pozhTrailers',
  labelSingular: 'Прицеп',
  labelPlural: 'Прицепы',
  description: 'Прицепы и полуприцепы. Цепляются к машине в путевом листе.',
  icon: 'IconCaravan',
  // Заголовок записи — регистрационный номер: другого короткого имени у прицепа
  // нет, марка у половины парка одинаковая.
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'registrationNumber'),
  fields: [
    текст({
      объект: О,
      имя: 'registrationNumber',
      подпись: 'Регистрационный номер',
      пояснение: 'Как в свидетельстве о регистрации. Уникален: держит от двойного заведения.',
      обязательно: true,
      уникально: true,
    }),
    текст({ объект: О, имя: 'brand', подпись: 'Марка' }),
    // «Серия» и «Код» — из старой базы. Что это, документ не объясняет, а
    // придумывать смысл нельзя: поля переносятся как есть, текстом, и разбираются
    // отдельно вместе с заказчиком.
    текст({
      объект: О,
      имя: 'series',
      подпись: 'Серия',
      пояснение: 'Из старой базы, переносится как есть.',
    }),
    текст({
      объект: О,
      имя: 'code',
      подпись: 'Код',
      пояснение: 'Код из старой системы. Нужен выгрузкам, которые ходят по старым кодам.',
    }),
    // Прицеп не удаляют, а гасят: его номер стоит в сданных путевых листах через
    // объект-связку, и удаление либо унесло бы строки листа, либо не прошло бы.
    флажок({
      объект: О,
      имя: 'isActive',
      подпись: 'Активен',
      пояснение: 'Снимите вместо удаления: номер прицепа стоит в уже сданных путевых листах.',
      поумолчанию: true,
    }),
    ...источник(О),
  ],
};
