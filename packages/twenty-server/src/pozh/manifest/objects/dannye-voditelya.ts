// пожсервис: объект «Персональные данные водителя» — СНИЛС, удостоверение,
// сроки. Отдельный объект, а не поля в справочнике водителей.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ОБЪЕКТ (решение 3 плана схемы, коротко и по делу).
// Запрет на отдельное поле в Twenty работает, но он двоичный: роль видит поле
// везде — в карточке, в списке, в выгрузке в файл — или не видит нигде.
// Разделения «в карточке показать, в списке не отдавать» в коде нет вовсе.
// А спрятать колонку из представления — не защита: любой сотрудник заводит своё
// личное представление и возвращает колонку обратно, права на это не нужны.
//
// Поэтому СНИЛС и номер удостоверения вынесены сюда. Тогда список водителей
// **физически не содержит** этих колонок — их неоткуда взять, и выгрузка
// водителей в файл безопасна по построению, а не по настройке. Доступ
// закрывается правом на объект (`canReadObjectRecords`), а оно действует во всех
// окнах сразу.
//
// ЧТО ЭТИМ НЕ ЗАКРЫТО, И ЭТО НАДО ЗНАТЬ. История изменений записи хранит
// «было / стало» по каждому полю и у наших объектов включена принудительно —
// выключить её описанием нечем. То есть СНИЛС не виден в карточке, но виден в
// истории её изменений (риск Р4 плана, решение владельца). И ещё: кто открывал
// карточку и смотрел СНИЛС, не записывается нигде — записи о чтении в Twenty нет.
//
// Разбор с полями — docs/russian-business/SCHEMA_PLAN.md, §4 и решение 3.

import {
  getIndexUniversalIdentifier,
  type IndexManifest,
  type ObjectManifest,
} from 'twenty-shared/application';
import { RelationOnDeleteAction } from 'twenty-shared/types';

import { ОБЪЕКТЫ, ПРИЛОЖЕНИЕ } from 'src/pozh/manifest/pozh-ids';
import { дата, источник, опознаватель, связь, текст } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.данныеВодителя;

/**
 * Связь «персональные данные → водитель». Половину-список забирает
 * `voditel.ts`, иначе выкладка упадёт: половинки описываются только парой.
 *
 * ЗАПРЕТИТЬ удаление водителя, пока у него есть эта запись. Обратное («удалять
 * по цепочке») выглядит удобно, но означает: удалили водителя — молча исчезли
 * его СНИЛС и удостоверение, а вместе с ними доказательство, что выписанные
 * путевые листы имели обязательные реквизиты. Водителей у нас вообще не
 * удаляют, их помечают неактивными, и запрет это закрепляет.
 */
export const связьПерсональныхДанныхСВодителем = связь({
  откуда: О,
  куда: ОБЪЕКТЫ.водитель,
  имяСсылки: 'driver',
  подписьСсылки: 'Водитель',
  имяСписка: 'personalData',
  подписьСписка: 'Персональные данные',
  приУдалении: RelationOnDeleteAction.RESTRICT,
  пояснение: 'Чей это набор персональных данных. У водителя набор ровно один.',
});

/**
 * «Один-к-одному» в Twenty отдельным видом связи не выражается — видов всего
 * два, «многие-к-одному» и «один-ко-многим». Поэтому один-к-одному собирается
 * так: обычная ссылка «многие-к-одному» отсюда на водителя плюс уникальный
 * указатель на неё. Тогда база сама не даст завести второй набор персональных
 * данных на того же человека (правило 4 плана схемы: ссылку в уникальный
 * указатель включать МОЖНО, если это ссылка «многие-к-одному» — она держит одну
 * колонку, и база её проиндексирует).
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ СПИСОК, А НЕ ПРИЗНАК У ПОЛЯ. Признак «уникально» у поля
 * для ссылок молча ничего не делает: обработчик, который заводит уникальный
 * указатель по признаку поля, для ссылок выходит сразу
 * (`field-unique-backing-index-on-create-side-effect-handler.service.ts` —
 * первым делом проверка `isMorphOrRelationUniversalFlatFieldMetadata` и выход).
 * Единственный работающий путь — описать указатель явно.
 *
 * ЭТО НАДО ВНЕСТИ В `pozh-manifest.ts`: указатели живут не внутри объекта, а
 * в поле `indexes` всего описания (`Manifest.indexes`). Без этого связь
 * останется «многие-к-одному», то есть на одного водителя можно будет завести
 * два набора персональных данных.
 */
export const указателиДанныхВодителя: IndexManifest[] = [
  {
    universalIdentifier: getIndexUniversalIdentifier({
      applicationUniversalIdentifier: ПРИЛОЖЕНИЕ,
      objectUniversalIdentifier: О,
      name: 'driverUnique',
    }),
    objectUniversalIdentifier: О,
    isUnique: true,
    fields: [
      {
        // Опознаватель самой строчки указателя. Переходник его не читает
        // (в базу уходит только ссылка на поле), но тип его требует, и он
        // обязан быть постоянным между выкладками, как и все остальные.
        universalIdentifier: getIndexUniversalIdentifier({
          applicationUniversalIdentifier: ПРИЛОЖЕНИЕ,
          objectUniversalIdentifier: О,
          name: 'driverUnique:driver',
        }),
        fieldUniversalIdentifier: опознаватель(О, 'driver'),
      },
    ],
  },
];

