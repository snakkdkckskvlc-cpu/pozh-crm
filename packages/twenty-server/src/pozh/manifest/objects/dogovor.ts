// пожсервис: объект «Договор обслуживания» — на основании чего мы обслуживаем
// объект заказчика, с какого по какое число и на какую сумму.
//
// Разбор с полями и почему они такие — docs/russian-business/SCHEMA_PLAN.md, §9.
// Про сумму — там же, «Решение 1»: деньги в проекте живут по отдельным правилам.

import { type ObjectFieldManifest, type ObjectManifest } from 'twenty-shared/application';
import { type FieldMetadataType } from 'twenty-shared/types';

import { связьОгнетушительДоговор } from 'src/pozh/manifest/objects/ognetushitel';
import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import {
  выбор,
  дата,
  деньги,
  источник,
  опознаватель,
  текст,
  флажок,
} from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.договор;

// Как часто по договору выезжаем и закрываемся актом. Значения списка выбора
// Twenty требует ЗАГЛАВНЫМИ с подчёркиваниями, человек видит подпись.
const периодичности = [
  { value: 'MONTH', label: 'Месяц', color: 'sky' },
  { value: 'QUARTER', label: 'Квартал', color: 'blue' },
  { value: 'YEAR', label: 'Год', color: 'purple' },
];

export const договор: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhServiceContract',
  namePlural: 'pozhServiceContracts',
  labelSingular: 'Договор обслуживания',
  labelPlural: 'Договоры обслуживания',
  description: 'На основании чего обслуживаем заказчика: срок, периодичность, сумма.',
  icon: 'IconFileDescription',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'number'),
  fields: [
    // Уникальность держит база, обязательность — служба документов. Вместе их
    // поставить нельзя (правило 4 плана схемы), и уникальность здесь важнее:
    // два договора с одним номером — это спор с заказчиком о том, какой из них
    // настоящий, а пустой номер видно глазами.
    текст({
      объект: О,
      имя: 'number',
      подпись: 'Номер договора',
      пояснение: 'Как записан в самом договоре. Повторяться не должен.',
      обязательно: true,
      уникально: true,
    }),
    // Переименовано с `object`: это имя входит в 63 запрещённых имени Twenty,
    // выкладка с ним не проходит. Подпись для человека осталась «Объект».
    текст({
      объект: О,
      имя: 'facility',
      подпись: 'Объект',
      пояснение: 'Что обслуживаем по этому договору: здание, площадка, адрес.',
    }),
    // ДЕНЬГИ. Красная линия проекта, поэтому подробно.
    //
    // Хранение: тип «Деньги» — единственный точный в Twenty. Обычное «Число»
    // становится колонкой с плавающей запятой и теряет копейки, а точный тип
    // NUMERIC руками создать не дают (решение 1). Единица хранения —
    // микро-рубль, одна миллионная рубля; копейка = 10 000 микро-рублей.
    //
    // Сумму кладёт служба документов ГОТОВЫМ ЦЕЛЫМ ЧИСЛОМ микро-рублей. Ввод с
    // экрана запрещён не из строгости: браузер умножает набранное на миллион
    // дробной арифметикой, и 8,11 ₽ превращается в 8 109 999,999999999 —
    // хвост потом отбрасывается. Потеря — доли копейки, но она есть.
    //
    // Дальше три настройки поверх помощника `деньги`, которых он сам не ставит:
    //
    // 1. `isUIEditable: false` — поле на экране только для чтения. Это защита от
    //    случайности, а НЕ запрет: признак работает в браузере, на сервере
    //    проверки нет. Настоящий запрет ставится правом роли на поле.
    // 2. `universalSettings` — как показывать. По умолчанию Twenty показывает
    //    деньги «сокращённо» и без копеек: бухгалтер увидел бы «1,2k» вместо
    //    «1 234,56 ₽». «Полностью» и два знака — обязательны (решение 1, п. 4).
    // 3. `defaultValue` с кодом валюты — рубль. Пустой код валюты означал бы
    //    сумму без единицы измерения; сама сумма при этом остаётся пустой.
    //
    // Сделать денежное поле обязательным или уникальным НЕЛЬЗЯ — подполя суммы
    // помечены необязательными в самом Twenty. Пробовать не надо.
    //
    // Приписка «как денежное» (`as`) нужна проверке типов, а не базе: помощник
    // возвращает «поле какого-нибудь вида», и к такому описанию нельзя дописать
    // настройки, которые есть только у денег. Сужаем до денежного — и дописываем.
    // Проверено: без этой приписки проверка типов отказывает.
    {
      ...(деньги({
        объект: О,
        имя: 'amount',
        подпись: 'Сумма договора',
        пояснение: 'Кладёт служба документов целым числом микро-рублей. С экрана не правится.',
      }) as ObjectFieldManifest<FieldMetadataType.CURRENCY>),
      isUIEditable: false,
      universalSettings: { format: 'full', decimals: 2 },
      defaultValue: { amountMicros: null, currencyCode: "'RUB'" },
    },
    // Значение по умолчанию — «Месяц», первый вариант из плана схемы: план
    // требует, чтобы пустой периодичности не было, но какая из трёх должна
    // подставляться, не называет. ПРОВЕРИТЬ на живых договорах: если
    // большинство квартальные, умолчание надо сменить (менять значения списка
    // выбора можно, правило 9).
    выбор({
      объект: О,
      имя: 'periodicity',
      подпись: 'Периодичность',
      пояснение: 'Как часто выезжаем и закрываемся актом.',
      варианты: периодичности,
      поумолчанию: 'MONTH',
    }),
    текст({
      объект: О,
      имя: 'subject',
      подпись: 'Предмет договора',
      пояснение: 'Что именно делаем: проверка, перезарядка, монтаж.',
    }),
    // Обе даты — не украшение карточки: за ними смотрит движок сроков (объект
    // «Правило срока»), и он умеет смотреть ТОЛЬКО на поля-даты. Отсюда же
    // требование заполнять их даже у бессрочных договоров.
    дата({
      объект: О,
      имя: 'validFrom',
      подпись: 'Действует с',
      пояснение: 'Начало действия. По этому полю правило срока предупреждает о начале обслуживания.',
    }),
    дата({
      объект: О,
      имя: 'validTo',
      подпись: 'Действует по',
      пояснение: 'Окончание действия. По нему правило срока предупреждает, что пора перезаключать.',
    }),
    // Вместо удаления. Договор попадает в сданные акты и счета, поэтому из базы
    // он не исчезает никогда — его просто снимают с галочки. То же правило, что
    // в старой базе: водитель с выписанными листами не удаляется, а гасится.
    флажок({
      объект: О,
      имя: 'isActive',
      подпись: 'Активен',
      пояснение: 'Снятая галочка заменяет удаление: договор перестаёт попадать в работу, но остаётся в истории.',
      поумолчанию: true,
    }),
    // Обратный список к ссылке, описанной в файле огнетушителя. Половинки связи
    // создаются одним вызовом помощника и раскладываются по двум объектам:
    // забытая половина роняет всю выкладку. При удалении договора огнетушители
    // остаются, ссылка обнуляется — разбор в ognetushitel.ts.
    связьОгнетушительДоговор.список,
    // ЗДЕСЬ ЖЕ ДОЛЖНА БЫТЬ ССЫЛКА «Контрагент» → Контрагент, при удалении
    // «запретить». Не описана потому, что объект «Контрагент» не мой — связь
    // сводится отдельно (перечислена в отчёте).
    ...источник(О),
  ],
};
