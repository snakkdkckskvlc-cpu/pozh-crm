// пожсервис: пункты меню для наших объектов.
//
// ЗАЧЕМ ОТДЕЛЬНО. Объект, созданный описанием, в базе появляется, а в меню —
// нет. Это ровно тот отказ, из-за которого в проекте заведено правило: **функция
// без входа для человека не существует.** Четырнадцать объектов были заведены,
// проверены запросом — и не видны никому, потому что в меню их не добавили.
// Проверено в браузере: список объектов через запрос отдавал наши четырнадцать,
// а в меню слева их не было ни одного.
//
// Порядок пунктов — по тому, как часто в них заходят, а не по алфавиту:
// контрагенты и договоры каждый день, счётчик номеров — никогда руками.

import {
  computeDeterministicUuid,
  type NavigationMenuItemManifest,
} from 'twenty-shared/application';
import { NavigationMenuItemType } from 'twenty-shared/types';

import { ОБЪЕКТЫ, ПРИЛОЖЕНИЕ } from 'src/pozh/manifest/pozh-ids';

const ПОРЯДОК: { объект: string; значок: string }[] = [
  { объект: ОБЪЕКТЫ.контрагент, значок: 'IconBuilding' },
  { объект: ОБЪЕКТЫ.договор, значок: 'IconFileDescription' },
  { объект: ОБЪЕКТЫ.огнетушитель, значок: 'IconFlame' },
  { объект: ОБЪЕКТЫ.движениеДокумента, значок: 'IconRoute' },
  { объект: ОБЪЕКТЫ.правилоСрока, значок: 'IconAlarm' },
  { объект: ОБЪЕКТЫ.путевойЛист, значок: 'IconClipboardText' },
  { объект: ОБЪЕКТЫ.рейс, значок: 'IconRoad' },
  { объект: ОБЪЕКТЫ.машина, значок: 'IconTruck' },
  { объект: ОБЪЕКТЫ.водитель, значок: 'IconUser' },
  { объект: ОБЪЕКТЫ.прицеп, значок: 'IconTrailer' },
  { объект: ОБЪЕКТЫ.точка, значок: 'IconMapPin' },
  // Служебные — внизу. Прячем их из меню не мы: у объекта-связки и счётчика
  // номеров смотреть не на что, но спрятать пункт можно и позже настройкой, а
  // вот отсутствующий пункт человек не найдёт никогда.
  { объект: ОБЪЕКТЫ.прицепВЛисте, значок: 'IconLink' },
  { объект: ОБЪЕКТЫ.счётчикНомеров, значок: 'IconHash' },
  { объект: ОБЪЕКТЫ.данныеВодителя, значок: 'IconLock' },
];

export const пунктыМеню: NavigationMenuItemManifest[] = ПОРЯДОК.map(
  ({ объект, значок }, номер) => ({
    universalIdentifier: computeDeterministicUuid({
      entityNamespace: 'navigationMenuItem',
      value: объект,
      applicationUniversalIdentifier: ПРИЛОЖЕНИЕ,
    }),
    type: NavigationMenuItemType.OBJECT,
    targetObjectUniversalIdentifier: объект,
    icon: значок,
    position: номер,
  }),
);
