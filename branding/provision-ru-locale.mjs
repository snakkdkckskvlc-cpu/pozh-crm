/**
 * Русские подписи, которые НЕ лежат в файлах и не переезжают сами.
 *
 * Файл стилей и словари переезжают через git — это код. Но названия наших
 * объектов («Сделки» вместо «Opportunities»), подписи «Кто создал» / «Когда
 * создал» на своих справочниках и удаление демонстрационной страницы «Star
 * History» — это ЗАПИСИ В БАЗЕ конкретного пространства, а не файлы. Свежая
 * база — своя ли на компьютере разработчика, боевая ли на сервере компании —
 * этих записей не содержит вовсе. Без этого скрипта после переноса на сервер
 * появится ровно та смесь языков, с которой всё и начиналось.
 *
 * ПОЧЕМУ ПОИСК ПО ИМЕНИ, А НЕ ПО НОМЕРУ ЗАПИСИ. Первая версия была написана
 * с зашитыми номерами объектов и видов — она сработала бы только на этой
 * машине, где эти номера совпадают случайно. На боевом сервере, где база
 * поднята заново, у тех же объектов будут другие номера. Поэтому каждая
 * запись здесь сначала находится по имени (nameSingular, name), и только
 * потом правится по найденному номеру.
 *
 * ПОЧЕМУ ЭТО НЕ ОДНОРАЗОВЫЙ СКРИПТ, А ПОВТОРЯЕМЫЙ. Прогнать один раз и
 * забыть нельзя: пространство переживёт сброс при переустановке, перенос
 * с тестового сервера на боевой, восстановление из резервной копии. Каждый
 * раз это будет заново английское пространство. Поэтому скрипт сначала
 * читает текущее состояние и трогает только то, что разошлось.
 *
 * ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ И ПОЧЕМУ. У КАЖДОГО объекта — своего и встроен-
 * ного — есть четыре графы «Кто создал», «Когда создал», «Кто изменил»,
 * «Когда изменил». У встроенных объектов Twenty подпись переводится на лету;
 * у своих объектов (Контрагенты, Огнетушители…) этот перевод не срабатывает,
 * и подписи остаются английскими — так устроена сама программа, не наша
 * недоделка. Починить это правкой текста не получится: сервер Twenty
 * НАМЕРЕННО отказывается менять подпись у системной графы, у любого объекта,
 * с явной ошибкой «Cannot edit system-managed field properties». Это не
 * забытая настройка, а осознанная защита, и обходить её прямой правкой базы
 * мы не стали — цена ошибки в обходе чужой защиты выше, чем польза от
 * четырёх переведённых подписей столбцов. Итог: эти четыре подписи у своих
 * объектов остаются английскими, и другого способа их перевести сейчас нет.
 *
 * ЗАПУСК. Нужен рабочий сервер Twenty (localhost:3000 или свой адрес) и
 * действующий ключ доступа — токен из входа администратора или ключ API из
 * настроек пространства (Settings → API keys, он не истекает, и для боевого
 * сервера годится лучше). Токен НЕ хранится в этом файле.
 *
 *   TWENTY_API_TOKEN=... node branding/provision-ru-locale.mjs
 *   TWENTY_API_TOKEN=... node branding/provision-ru-locale.mjs --проверить
 *   TWENTY_API_TOKEN=... TWENTY_API_URL=https://crm.pozhservis.ru node branding/provision-ru-locale.mjs
 */

const АДРЕС = (process.env.TWENTY_API_URL || 'http://localhost:3000') + '/metadata';
const ТОКЕН = process.env.TWENTY_API_TOKEN;
const ПРОВЕРКА = process.argv.includes('--проверить');

if (!ТОКЕН) {
  console.error('Нужен ключ доступа: TWENTY_API_TOKEN=... node branding/provision-ru-locale.mjs');
  console.error('Возьмите его после входа администратором (localStorage → tokenPairState)');
  console.error('или заведите постоянный ключ в настройках пространства (API keys).');
  process.exit(1);
}

async function зов(query, variables = {}) {
  const ответ = await fetch(АДРЕС, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${ТОКЕН}` },
    body: JSON.stringify({ query, variables }),
  });
  const тело = await ответ.json();
  if (тело.errors) throw new Error(JSON.stringify(тело.errors).slice(0, 300));
  return тело.data;
}

// --- 1. Подписи объектов ------------------------------------------------
//
// Служебное имя (nameSingular) остаётся латинским: на него завязаны адреса
// страниц и перенос данных из старой базы. Меняется только то, что видит
// человек — единственное и множественное число.
const ПОДПИСИ_ОБЪЕКТОВ = {
  opportunity: ['Сделка', 'Сделки'],
  task: ['Задача', 'Задачи'],
  note: ['Заметка', 'Заметки'],
  dashboard: ['Сводка', 'Сводки'],
  workflow: ['Автоматизация', 'Автоматизации'],
  employmentHistory: ['Место работы', 'Места работы'],
  person: ['Человек', 'Люди'],
  company: ['Компания', 'Компании'],
};

// --- 2. Названия видов списка --------------------------------------------
const ПОДПИСИ_ВИДОВ = {
  'All {objectLabelPlural}': 'Все {objectLabelPlural}',
  'Assigned to Me': 'Мои',
  'By Stage': 'По этапам',
  'By Status': 'По состоянию',
  Runs: 'Запуски',
  Versions: 'Версии',
};

// --- 3. Папка меню и демонстрационная страница ---------------------------
const ПАПКА_МЕНЮ = { было: 'Workflows', стало: 'Автоматизации' };
const УДАЛИТЬ_ПУНКТ_МЕНЮ = 'Star History';

// --- 4. Команды палитры (⌘K) и панели действий ---------------------------
//
// Кнопка «+ Контрагент» в углу списка — не текст программы, а ШАБЛОН КОМАНДЫ,
// который хранится в базе отдельно от названий объектов, видов и меню (третье
// такое место после них). Того же рода команды стоят за правой кнопкой
// действий, за палитрой быстрых действий (сочетание ⌘K) и за пунктами
// контекстного меню записи — 70 разных подписей и 62 коротких, по одной
// заготовке на тип действия, а не по одной на объект.
//
// РОД И ПАДЕЖ. Английское «New X» не согласуется с X никак, а русское
// «Новый X» требует рода: «Новый Контрагент», но «Новая Задача», «Новое
// Правило» — один жёсткий шаблон дал бы неправильный род на части объектов.
// Поэтому заготовки построены так, чтобы род названия объекта не имел
// значения: «Новая запись: {X}», «Удалить: {X}», «Экспортировать: {X}» —
// перед двоеточием стоит слово, не зависящее от X, а не согласованное
// прилагательное.
//
// Подстановки вида ${capitalize(objectMetadataItem.labelSingular)} — это код
// на JavaScript внутри текста, который сама программа выполняет при показе
// команды. Их нельзя ни переводить, ни менять ни на один символ — сломается
// подстановка настоящего названия объекта. Заготовки ниже это соблюдают,
// проверено сверкой строка в строку перед вставкой в файл.
const КОМАНДЫ = JSON.parse(
  await (await import('node:fs/promises')).readFile(
    new URL('./command-templates.json', import.meta.url),
  ),
);

const итог = { сделано: [], пропущено: 0, ошибок: 0 };
const отметить = (текст) => { итог.сделано.push(текст); console.log(`  ✔ ${текст}`); };
const беда = (текст) => { итог.ошибок++; console.error(`  ✖ ${текст}`); };

async function загрузитьОбъекты() {
  const { objects } = await зов(`{
    objects(paging: {first: 200}) {
      edges { node { id nameSingular labelSingular labelPlural } }
    }
  }`);
  return objects.edges.map((e) => e.node);
}

async function правитьОбъекты(объекты) {
  for (const [имя, [ед, мн]] of Object.entries(ПОДПИСИ_ОБЪЕКТОВ)) {
    const о = объекты.find((x) => x.nameSingular === имя);
    if (!о) { беда(`объект «${имя}» не найден — Twenty мог его переименовать`); continue; }
    if (о.labelSingular === ед && о.labelPlural === мн) { итог.пропущено++; continue; }
    if (ПРОВЕРКА) { отметить(`(проверка) объект «${имя}»: «${о.labelPlural}» → «${мн}»`); continue; }
    await зов(
      `mutation($id:UUID!,$u:UpdateObjectPayload!){ updateOneObject(input:{id:$id, update:$u}){ id } }`,
      { id: о.id, u: { labelSingular: ед, labelPlural: мн } },
    );
    отметить(`объект «${имя}»: «${о.labelPlural}» → «${мн}»`);
  }
}

async function правитьВиды() {
  const { getViews } = await зов(`{ getViews { id name } }`);
  for (const вид of getViews) {
    const нужно = ПОДПИСИ_ВИДОВ[вид.name];
    if (!нужно) { continue; }
    if (ПРОВЕРКА) { отметить(`(проверка) вид «${вид.name}» → «${нужно}»`); continue; }
    await зов(
      `mutation($id:String!,$i:UpdateViewInput!){ updateView(id:$id, input:$i){ id } }`,
      { id: вид.id, i: { name: нужно } },
    );
    отметить(`вид «${вид.name}» → «${нужно}»`);
  }
}

async function правитьМеню() {
  const { navigationMenuItems: пункты } = await зов(
    `{ navigationMenuItems { id name type pageLayoutId } }`,
  );

  const папка = пункты.find((p) => p.type === 'FOLDER' && p.name === ПАПКА_МЕНЮ.было);
  if (папка) {
    if (ПРОВЕРКА) отметить(`(проверка) папка «${ПАПКА_МЕНЮ.было}» → «${ПАПКА_МЕНЮ.стало}»`);
    else {
      await зов(
        `mutation($i:UpdateOneNavigationMenuItemInput!){ updateNavigationMenuItem(input:$i){ id } }`,
        { i: { id: папка.id, update: { name: ПАПКА_МЕНЮ.стало } } },
      );
      отметить(`папка «${ПАПКА_МЕНЮ.было}» → «${ПАПКА_МЕНЮ.стало}»`);
    }
  } else итог.пропущено++;

  const демо = пункты.find((p) => p.name === УДАЛИТЬ_ПУНКТ_МЕНЮ);
  if (демо) {
    if (ПРОВЕРКА) { отметить(`(проверка) удалить пункт меню и страницу «${УДАЛИТЬ_ПУНКТ_МЕНЮ}»`); return; }
    await зов(`mutation($id:UUID!){ deleteNavigationMenuItem(id:$id){ id } }`, { id: демо.id });
    if (демо.pageLayoutId) {
      await зов(`mutation($id:String!){ destroyPageLayout(id:$id) }`, { id: демо.pageLayoutId });
    }
    отметить(`удалены пункт меню и страница «${УДАЛИТЬ_ПУНКТ_МЕНЮ}» (выход на внешний сайт в офлайн-программе)`);
  } else итог.пропущено++;
}

async function правитьКоманды() {
  const { commandMenuItems: команды } = await зов(
    `{ commandMenuItems { id label shortLabel } }`,
  );
  for (const к of команды) {
    const новыйLabel = КОМАНДЫ.label[к.label];
    const новыйShort = к.shortLabel != null ? КОМАНДЫ.shortLabel[к.shortLabel] : undefined;
    const правка = {};
    if (новыйLabel && новыйLabel !== к.label) правка.label = новыйLabel;
    if (новыйShort && новыйShort !== к.shortLabel) правка.shortLabel = новыйShort;
    if (!Object.keys(правка).length) { if (новыйLabel || новыйShort) итог.пропущено++; continue; }
    const было = [к.label, к.shortLabel].filter(Boolean).join(' / ');
    const стало = [правка.label ?? к.label, правка.shortLabel ?? к.shortLabel].filter(Boolean).join(' / ');
    if (ПРОВЕРКА) { отметить(`(проверка) команда «${было}» → «${стало}»`); continue; }
    await зов(
      `mutation($i:UpdateCommandMenuItemInput!){ updateCommandMenuItem(input:$i){ id } }`,
      { i: { id: к.id, ...правка } },
    );
    отметить(`команда «${было}» → «${стало}»`);
  }
}

async function main() {
  console.log(ПРОВЕРКА ? 'ПРОВЕРКА (ничего не меняю)' : 'РУСИФИКАЦИЯ ДАННЫХ ПРОСТРАНСТВА');
  console.log('='.repeat(40));

  await правитьОбъекты(await загрузитьОбъекты());
  await правитьВиды();
  await правитьМеню();
  await правитьКоманды();

  console.log('');
  console.log(`Сделано: ${итог.сделано.length}. Уже было верно: ${итог.пропущено}. Ошибок: ${итог.ошибок}.`);
  if (итог.ошибок) process.exit(1);
}

main().catch((e) => { console.error('Остановлено:', e.message); process.exit(1); });
