/**
 * Перекрашивает Twenty в фирменные цвета ООО «ПожСервис».
 *
 * ПОЧЕМУ СКРИПТ, А НЕ ПРАВКА РУКАМИ. Фирменного вида настройкой в Twenty нет:
 * основной цвет собран из палитры в исходниках (packages/twenty-ui/src/theme).
 * Значит это правка ядра — самая нижняя ступень лестницы расширения, и её цена
 * в том, что при каждом обновлении Twenty её надо накладывать заново.
 *
 * Скрипт делает эту цену подъёмной: обновились — прогнали снова. Правки руками
 * при обновлении теряются молча, и приложение вдруг оказывается синим.
 *
 * ТРИ СВОЙСТВА, БЕЗ КОТОРЫХ СКРИПТ БЫЛ БЫ ВРЕДЕН:
 *
 * 1. Повторяемость. Прогон дважды не ломает файл и ничего не удваивает: перед
 *    правкой ищется уже наложенная метка.
 * 2. Проверяемость. Скрипт говорит, что именно поменял, и отдельно называет то,
 *    чего не нашёл. Молча «ничего не изменилось» — худший исход: человек решит,
 *    что покрасил, а Twenty останется синим.
 * 3. Обратимость. Рядом с каждым тронутым файлом кладётся копия «.pozh-backup»,
 *    и `--откатить` возвращает всё как было.
 *
 * Запуск:
 *   node branding/apply-branding.mjs            — перекрасить
 *   node branding/apply-branding.mjs --проверить — только показать, что сделал бы
 *   node branding/apply-branding.mjs --откатить  — вернуть как было
 */

import { readFileSync, writeFileSync, existsSync, copyFileSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), '..');
const TWENTY = join(КОРЕНЬ, 'twenty');
const МАРКА = JSON.parse(readFileSync(join(КОРЕНЬ, 'branding', 'pozh-brand.json'), 'utf8'));

// Метка, по которой скрипт узнаёт свою же работу. Без неё повторный прогон
// накладывал бы правку на правку.
const МЕТКА = '/* пожсервис: фирменный вид */';

const режим = process.argv.includes('--откатить')
  ? 'откат'
  : process.argv.includes('--проверить')
    ? 'проверка'
    : 'правка';

const ступени = МАРКА._ступени_красного;

/** Правки: файл → что заменить. Каждая правка объяснена. */
const ПРАВКИ = [
  {
    файл: 'packages/twenty-ui/src/theme/constants/MainColorsLight.ts',
    зачем:
      'Основной цвет интерфейса. Twenty зовёт его «blue» и берёт из чужой палитры; ' +
      'подменяем значение, а не имя — имя разбросано по сотням мест.',
    правки: [
      {
        было: /blue: RadixColors\.indigoP3\.indigo9,/,
        стало: `blue: '${ступени['9']}', ${МЕТКА}`,
      },
    ],
  },
  {
    файл: 'packages/twenty-ui/src/theme/constants/AccentLight.ts',
    зачем:
      'Оттенки выделения: подложка кнопки, наведение, рамка активного поля. ' +
      'Берутся из синего семейства — переводим на наши ступени.',
    правки: [
      { было: /primary: COLOR_LIGHT\.blue5,/, стало: `primary: '${ступени['5']}', ${МЕТКА}` },
      { было: /secondary: COLOR_LIGHT\.blue5,/, стало: `secondary: '${ступени['5']}',` },
      { было: /tertiary: COLOR_LIGHT\.blue3,/, стало: `tertiary: '${ступени['3']}',` },
      { было: /quaternary: COLOR_LIGHT\.blue2,/, стало: `quaternary: '${ступени['2']}',` },
      { было: /accent3570: COLOR_LIGHT\.blue8,/, стало: `accent3570: '${ступени['8']}',` },
      { было: /accent4060: COLOR_LIGHT\.blue8,/, стало: `accent4060: '${ступени['8']}',` },
    ],
  },
];

const результат = { тронуто: [], пропущено: [], ненайдено: [] };

for (const { файл, зачем, правки } of ПРАВКИ) {
  const путь = join(TWENTY, файл);
  const копия = `${путь}.pozh-backup`;

  if (!existsSync(путь)) {
    результат.ненайдено.push(`${файл} — файла нет. Twenty переехал? Правку надо переписать.`);
    continue;
  }

  if (режим === 'откат') {
    if (existsSync(копия)) {
      copyFileSync(копия, путь);
      unlinkSync(копия);
      результат.тронуто.push(`${файл} — возвращён`);
    } else {
      результат.пропущено.push(`${файл} — копии нет, возвращать нечего`);
    }
    continue;
  }

  let текст = readFileSync(путь, 'utf8');

  if (текст.includes(МЕТКА)) {
    результат.пропущено.push(`${файл} — уже покрашен`);
    continue;
  }

  const непримененные = [];
  let новый = текст;
  for (const { было, стало } of правки) {
    if (!было.test(новый)) {
      непримененные.push(было.source);
      continue;
    }
    новый = новый.replace(было, стало);
  }

  if (непримененные.length) {
    // Частично наложенная правка хуже неналоженной: половина интерфейса красная,
    // половина синяя, и понять почему нельзя. Поэтому файл не трогаем вовсе.
    результат.ненайдено.push(
      `${файл} — не нашлось ${непримененные.length} из ${правки.length} кусков:\n      ` +
        непримененные.join('\n      ') +
        '\n      Файл НЕ тронут. Скорее всего Twenty изменил тему — правку надо переписать.',
    );
    continue;
  }

  if (режим === 'проверка') {
    результат.тронуто.push(`${файл} — покрасился бы (${правки.length} мест). ${зачем}`);
    continue;
  }

  if (!existsSync(копия)) copyFileSync(путь, копия);
  writeFileSync(путь, новый, 'utf8');
  результат.тронуто.push(`${файл} — покрашен (${правки.length} мест)`);
}

const заголовок = { правка: 'ПЕРЕКРАШЕНО', проверка: 'ПРОВЕРКА (ничего не менялось)', откат: 'ОТКАЧЕНО' }[режим];
console.log(`\n${заголовок}\n${'='.repeat(заголовок.length)}`);
for (const с of результат.тронуто) console.log(`  ✔ ${с}`);
for (const с of результат.пропущено) console.log(`  · ${с}`);
for (const с of результат.ненайдено) console.log(`  ✖ ${с}`);

if (результат.ненайдено.length) {
  console.log(
    '\nЧасть правок не наложилась. Это НЕ «почти получилось»: интерфейс останется\n' +
      'прежним, и молчать об этом нельзя. Разберитесь, что изменилось в Twenty.',
  );
  process.exit(1);
}
if (!результат.тронуто.length && режим === 'правка') {
  console.log('\nНичего не поменялось — всё уже покрашено.');
}
console.log('');
