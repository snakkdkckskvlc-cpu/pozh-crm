/**
 * ПОЛИТИКА СОДЕРЖИМОГО СТРАНИЦЫ. Правка форка ПожСервиса.
 *
 * ЗАЧЕМ ПРОВЕРКА. Запрет в коде (pozh-netguard.ts) закрывает серверную половину.
 * Браузерную закрывает правило в index.html — и оно живёт обычной строкой в
 * разметке: его легко смягчить одной правкой, и никто не заметит. Ровно это и
 * случилось: в правило добавили «ws: wss:» — схемы БЕЗ адреса, то есть
 * разрешение открыть постоянное соединение с любым сервером в интернете.
 * Остальные строки при этом выглядели строгими, и дыра была не видна:
 * картинку с чужого сервера браузер бы не взял, а соединение с ним — взял бы.
 *
 * Поэтому здесь проверяется не «правило есть», а что в нём нет разрешений
 * «куда угодно».
 */

import fs from 'node:fs';
import path from 'node:path';

const СТРАНИЦА = path.join(
  __dirname,
  '..',
  '..',
  '..',
  'twenty-front',
  'index.html',
);

/** Значение правила без окружающих комментариев: они тоже упоминают схемы. */
const правило = (): string => {
  const разметка = fs
    .readFileSync(СТРАНИЦА, 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '');
  const найдено = разметка.match(
    /http-equiv="Content-Security-Policy"\s*content="([^"]+)"/,
  );

  if (!найдено) throw new Error('в index.html нет политики содержимого страницы');

  return найдено[1];
};

const источники = (директива: string): string[] => {
  const часть = правило()
    .split(';')
    .map((с) => с.trim())
    .find((с) => с.startsWith(`${директива} `));

  return часть ? часть.slice(директива.length).trim().split(/\s+/) : [];
};

describe('политика содержимого страницы закрывает браузер', () => {
  it('соединения разрешены только со своей машиной', () => {
    const разрешено = источники('connect-src');

    expect(разрешено.length).toBeGreaterThan(0);
    for (const источник of разрешено) {
      const свой =
        источник === "'self'" ||
        /^wss?:\/\/(localhost|127\.0\.0\.1)(:\*|:\d+)?$/.test(источник) ||
        /^https?:\/\/(localhost|127\.0\.0\.1)(:\*|:\d+)?$/.test(источник);

      expect(свой).toBe(true);
    }
  });

  it('нет разрешений «любой адрес по этой схеме»', () => {
    // «ws:», «wss:», «https:» без адреса разрешают весь интернет по этой схеме.
    // Выглядит почти как ограничение, а работает наоборот.
    const голаяСхема = /(^|\s)(wss?|https?|data|blob):(\s|;|$)/;
    for (const директива of ['connect-src', 'script-src', 'frame-src']) {
      for (const источник of источники(директива)) {
        expect(источник).not.toMatch(/^(wss?|https?):$/);
      }
    }
    expect(правило().match(голаяСхема)?.[2]).not.toMatch(/^wss?$/);
  });

  it('чужие адреса не подмешаны ни в одну строку правила', () => {
    // Кроме подстановки %POZH_DOCS_ORIGIN% — её значение задаётся при сборке и
    // указывает на свою же службу документов.
    const чужой = /(https?|wss?):\/\/(?!localhost|127\.0\.0\.1)[a-z0-9-]+\.[a-z]/i;

    expect(правило().replace('%POZH_DOCS_ORIGIN%', '')).not.toMatch(чужой);
  });
});
