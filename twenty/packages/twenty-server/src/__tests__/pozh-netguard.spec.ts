/**
 * Запрет выхода в интернет.
 *
 * Половина файла проверяет, что СВОИ адреса проходят молча. Запрет, который
 * иногда отвергает своих, хуже отсутствующего: его отключат целиком при первой
 * же непонятной поломке.
 *
 * Вторая половина проверяет, что чужие не проходят никаким способом — включая
 * те, которыми запрет обходят случайно: обёрнутый адрес шестой версии, адрес
 * вместо имени, поддомен разрешённого имени.
 */

import { адресРазрешён } from 'src/pozh-netguard';

describe('запрет выхода в интернет', () => {
  describe('свои адреса проходят', () => {
    it.each([
      ['localhost', 'своя машина по имени'],
      ['127.0.0.1', 'своя машина по адресу'],
      ['::1', 'своя машина, шестая версия'],
      ['10.0.0.5', 'частная сеть предприятия'],
      ['172.16.4.1', 'частная сеть, нижняя граница'],
      ['172.31.255.254', 'частная сеть, верхняя граница'],
      ['192.168.1.10', 'домашняя и офисная сеть'],
      ['169.254.1.1', 'самоназначенный адрес'],
      ['::ffff:192.168.1.10', 'частный адрес, обёрнутый в шестую версию'],
      ['fd00::1', 'частный адрес шестой версии'],
    ])('%s — %s', (адрес) => {
      expect(адресРазрешён(адрес)).toBe(true);
    });

    it('обращение без имени — это внутри процесса, не наружу', () => {
      expect(адресРазрешён(undefined)).toBe(true);
    });
  });

  describe('чужие адреса не проходят', () => {
    it.each([
      ['twenty-telemetry.com', 'телеметрия Twenty — включена по умолчанию в исходном коде'],
      ['api.twenty.com', 'обращение к разработчику'],
      ['sentry.io', 'сборщик ошибок'],
      ['www.googleapis.com', 'чужие службы'],
      ['8.8.8.8', 'чужой адрес напрямую'],
      ['172.15.0.1', 'соседний с частным диапазоном — но чужой'],
      ['172.32.0.1', 'соседний с частным диапазоном сверху — но чужой'],
      ['11.0.0.1', 'соседний с частной десяткой — но чужой'],
      ['192.169.1.1', 'похож на частный, но чужой'],
    ])('%s — %s', (адрес) => {
      expect(адресРазрешён(адрес)).toBe(false);
    });

    it('главный случай: телеметрия Twenty отвергается', () => {
      // В исходном Twenty TELEMETRY_ENABLED = true по умолчанию, и события о
      // работе уходят на этот адрес. Для системы с документами заказчика это
      // прямое нарушение договора о конфиденциальности.
      expect(адресРазрешён('twenty-telemetry.com')).toBe(false);
    });
  });

  describe('список разрешённых имён', () => {
    const исходный = process.env.POZH_ALLOWED_HOSTS;
    afterEach(() => {
      process.env.POZH_ALLOWED_HOSTS = исходный;
      jest.resetModules();
    });

    it('разрешение по имени распространяется на поддомены', async () => {
      process.env.POZH_ALLOWED_HOSTS = 'nlmk.local';
      jest.resetModules();
      const { адресРазрешён: свежий } = await import('src/pozh-netguard');
      expect(свежий('nlmk.local')).toBe(true);
      expect(свежий('почта.nlmk.local')).toBe(true);
      // Но не на имя, которое лишь ЗАКАНЧИВАЕТСЯ похоже: «злойnlmk.local»
      // не является поддоменом, и пускать его нельзя.
      expect(свежий('злойnlmk.local')).toBe(false);
    });

    it('пустой список по умолчанию: разрешение выдаётся поимённо', async () => {
      delete process.env.POZH_ALLOWED_HOSTS;
      jest.resetModules();
      const { адресРазрешён: свежий } = await import('src/pozh-netguard');
      expect(свежий('example.com')).toBe(false);
    });
  });

  describe('текст отказа', () => {
    it('написан для человека и говорит, что делать', async () => {
      const { ВыходНаружуЗапрещён } = await import('src/pozh-netguard');
      const текст = new ВыходНаружуЗапрещён('twenty-telemetry.com').message;
      // Сообщение читает не программист. Слов «сокет», «DNS», «прокси» быть не
      // должно, а должно быть сказано, куда пытались и что делать.
      for (const запрещено of ['socket', 'сокет', 'DNS', 'proxy', 'прокси']) {
        expect(текст.toLowerCase()).not.toContain(запрещено.toLowerCase());
      }
      expect(текст).toContain('twenty-telemetry.com');
      expect(текст).toContain('POZH_ALLOWED_HOSTS');
    });
  });
});
