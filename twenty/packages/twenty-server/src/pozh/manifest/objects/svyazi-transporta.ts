// пожсервис: связи транспорта — все пары в одном месте.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Помощник `связь` отдаёт обе половины сразу: ссылку у
// того, кто ссылается, и обратный список у того, на кого ссылаются. Половины
// живут в разных объектах, и если объявлять пару внутри файла объекта, файлы
// начинают ссылаться друг на друга по кругу: рейс знает про машину, машина —
// про рейс. Здесь пары объявлены один раз, а файлы объектов только разбирают их
// по половинкам. Каждая половина попадает в описание ровно один раз — забытая
// вторая роняет всю выкладку.
//
// ПРО «ЧТО ДЕЛАТЬ ПРИ УДАЛЕНИИ». Настройка обязательна у каждой пары (правило 5
// плана схемы): описание в коде передаёт настройки как есть, а сервер при
// отсутствии настройки молча подставляет «удалить по цепочке». То есть забытая
// строчка превращает удаление одной машины в исчезновение всех её рейсов.
// Поэтому у каждой пары ниже написано, почему выбрано именно это.

import { type ObjectFieldManifest } from 'twenty-shared/application';
import { RelationOnDeleteAction } from 'twenty-shared/types';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { связь } from 'src/pozh/manifest/pozh-pole';

// Машина принадлежит нашей организации («ПожСервис» или «ПожМастер») — она же
// печатается в шапке путевого листа.
//
// ЗАПРЕТИТЬ. Организация уходит в сданные документы: удалив контрагента, мы
// оставили бы выписанные листы без того, от чьего имени они выписаны. Пусть
// база не даст удалить — контрагент гасится признаком, а не удалением.
export const организацияМашины = связь({
  откуда: ОБЪЕКТЫ.машина,
  куда: ОБЪЕКТЫ.контрагент,
  имяСсылки: 'organization',
  подписьСсылки: 'Организация',
  имяСписка: 'vehicles',
  подписьСписка: 'Машины',
  приУдалении: RelationOnDeleteAction.RESTRICT,
  пояснение: 'Наша организация, от имени которой ездит машина. Попадает в шапку путевого листа.',
});

// Рейс совершает конкретная машина.
//
// ЗАПРЕТИТЬ. Рейс — основание для списания топлива и строка путевого листа.
// «Обнулить» дало бы рейс без машины: пробег и топливо есть, а чьи — неизвестно,
// и закрытый месяц перестаёт сходиться. Машина не удаляется, а гасится
// признаком «Активна» — ровно как в старой базе.
export const машинаРейса = связь({
  откуда: ОБЪЕКТЫ.рейс,
  куда: ОБЪЕКТЫ.машина,
  имяСсылки: 'vehicle',
  подписьСсылки: 'Машина',
  имяСписка: 'trips',
  подписьСписка: 'Рейсы',
  приУдалении: RelationOnDeleteAction.RESTRICT,
  пояснение: 'Машина, которая ездила в этот рейс.',
});

// Откуда выехали.
//
// ОБНУЛИТЬ. Точка — справочник удобства: её заводят, переименовывают и
// вычищают, чтобы список не разрастался. Рейс без точки отправления остаётся
// полноценной записью (время, пробег и топливо при ней), а исчезнувший рейс —
// это дыра в путевом листе. Поэтому запись живёт, ссылка стирается.
export const откудаРейса = связь({
  откуда: ОБЪЕКТЫ.рейс,
  куда: ОБЪЕКТЫ.точка,
  имяСсылки: 'departurePoint',
  подписьСсылки: 'Откуда',
  имяСписка: 'departingTrips',
  подписьСписка: 'Рейсы отсюда',
  приУдалении: RelationOnDeleteAction.SET_NULL,
  пояснение: 'Точка отправления из справочника. Пусто — значит выезд отмечен без справочника.',
});

// Куда приехали.
//
// ОБНУЛИТЬ — по той же причине, что и «Откуда». Плюс у рейса есть запасное
// текстовое поле «Адрес назначения»: куда ездили, известно и без справочника,
// поэтому потеря ссылки не потеря сведений.
export const кудаРейса = связь({
  откуда: ОБЪЕКТЫ.рейс,
  куда: ОБЪЕКТЫ.точка,
  имяСсылки: 'arrivalPoint',
  подписьСсылки: 'Куда',
  имяСписка: 'arrivingTrips',
  подписьСписка: 'Рейсы сюда',
  приУдалении: RelationOnDeleteAction.SET_NULL,
  пояснение: 'Точка назначения из справочника. Если её там нет — заполняется «Адрес назначения».',
});

/**
 * Половины, которые принадлежат объектам НЕ из этого набора.
 *
 * Обратный список «Машины» живёт у контрагента, а файл контрагента пишу не я.
 * Половина не может остаться нигде: выкладка ищет вторую половину по
 * опознавателю и без неё падает. Поэтому она вынесена сюда — тому, кто
 * собирает описание, остаётся добавить её в поля контрагента одной строкой:
 *
 *   ...половиныДляЧужихОбъектов
 *
 * (или положить в общий список `fields` манифеста — она уже знает, какому
 * объекту принадлежит).
 */
export const половиныДляЧужихОбъектов: ObjectFieldManifest[] = [
  организацияМашины.список,
];
