// пожсервис: связи внутри снабжения — все в одном месте.
//
// ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. У связи две половины: ссылка на одной записи и список
// на другой. Если объявлять их в файлах объектов, половины разъезжаются —
// правишь одну, забываешь вторую, и Twenty при выкладке ругается на связь,
// у которой нет ответной стороны. Здесь пара всегда объявлена целиком, а объект
// берёт из неё свою половину по имени.
//
// Тот же приём уже применён к транспорту, `svyazi-transporta.ts`.
//
// ЧТО ПРОИСХОДИТ ПРИ УДАЛЕНИИ — решается по каждой связи отдельно и вслух:
//
//   CASCADE  — строка без своей шапки смысла не имеет (позиция заявки без
//              заявки, строка справки без справки).
//   RESTRICT — удалить не дадут: за записью тянутся движения и деньги
//              (стройобъект, остаток).
//   SET_NULL — ссылка обнуляется, запись живёт: заявка без позиции
//              спецификации — обычное дело, прораб просит то, чего в проекте
//              нет, и это как раз то, ради чего заведена подсветка перебора.

