// пожсервис: объект «Позиция спецификации» — строка проекта.
//
// ЗАЧЕМ. Слова владельца на показе 26.08.2026: «мы знаем, что сюда нужен вот
// такой-то материал, в таком-то количестве и с такими-то ценами договорными.
// Для чего? Чтобы не купить больше, как минимум. Раз — чтобы не купить дороже».
// Отсюда два поля-лимита и договорная цена: без них подсветка перебора не
// с чем сравнивать.
//
// ПРО ИЗМ. Изменение к проекту не заводит новую строку, а меняет количество в
// этой: «ИЗМ может ещё и уменьшить». Поэтому у количества нет истории правок —
// её ведёт сам Twenty, а нам нужна текущая цифра, с которой сравнивают.

import { type ObjectManifest } from 'twenty-shared/application';

import {
  позицияЗаявкиПоСпецификации,
  спецификацияОбъекта,
} from 'src/pozh/manifest/objects/svyazi-snabzheniya';
import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { деньги, источник, опознаватель, текст, число } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.позицияСпецификации;

export const позицияСпецификации: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhSpecLine',
  namePlural: 'pozhSpecLines',
  labelSingular: 'Позиция спецификации',
  labelPlural: 'Спецификация',
  description: 'Строка проекта: что, сколько и по какой договорной цене заложено на объект.',
  icon: 'IconListNumbers',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'name'),
  fields: [
    текст({
      объект: О,
      имя: 'name',
      подпись: 'Наименование',
      пояснение: 'Как позиция записана в спецификации, слово в слово. По этой строке потом ищут совпадение.',
      обязательно: true,
    }),
    текст({
      объект: О,
      имя: 'unit',
      подпись: 'Единица',
      пояснение: 'м, шт, кг, компл — как в спецификации.',
    }),
    // Количество в тысячных долях единицы, целым числом. Причина та же, по
    // которой расстояние в точке хранится в метрах: дробное число копит ошибку
    // от строки к строке, а спецификацию потом складывают с приходами и
    // списаниями. 97,5 м записывается как 97500.
    число({
      объект: О,
      имя: 'plannedQtyMilli',
      подпись: 'По проекту (тысячные)',
      пояснение: 'Целое число тысячных долей единицы: 97,5 м — это 97500. Дробное здесь копило бы ошибку.',
      обязательно: true,
    }),
    // Договорная цена. Хранится как деньги Twenty, но вводить её штатным
    // экраном нельзя: он теряет копейки (риск 5 карты работ). Своя форма
    // обязательна, поэтому поле помечено как не правимое руками.
    деньги({
      объект: О,
      имя: 'contractPrice',
      подпись: 'Цена по договору',
      пояснение: 'Вводится только своей формой: штатный экран Twenty теряет копейки.',
    }),
    текст({
      объект: О,
      имя: 'changeOrder',
      подпись: 'Каким ИЗМ изменено',
      пояснение: 'Номер изменения к проекту, если количество уже правили. Пусто — значит стоит исходное.',
    }),
    спецификацияОбъекта.ссылка,
    позицияЗаявкиПоСпецификации.список,
    ...источник(О),
  ],
};
