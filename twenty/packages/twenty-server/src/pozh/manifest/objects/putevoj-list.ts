//
// 1. У черновика номера НЕТ и быть не должно. Номер присваивается в момент
//    выписки, из отдельного счётчика (`schetchik-nomerov.ts`). Поэтому «Номер»
//    здесь необязательный, а уникальный: PostgreSQL считает пустые значения
//    различными, то есть черновиков без номера может быть сколько угодно, а
//    второй лист с номером 4417 база не пропустит. Проверено опытом на нашей
//    базе, не рассуждением.
//
// 2. Путевые листы НЕ УДАЛЯЮТСЯ. Ни секретарём, ни администратором: удаление
//    выключается правами на объект (`canSoftDeleteObjectRecords` и
//    `canDestroyObjectRecords` в описании роли — `objectPermissions`), а запрет
//    на объекте перекрывает общее разрешение роли «может удалять всё».
//    Ошибочный лист аннулируется: состояние «аннулирован», дата и причина.
//    Номер при этом остаётся занятым навсегда — так и положено бланку строгой
//    отчётности, повтор номера делает документ недействительным.
//    Права описываются в роли, а не здесь; в этом файле их выразить нечем.
//
// Разбор с полями — docs/russian-business/SCHEMA_PLAN.md, §8 и решение 2.

