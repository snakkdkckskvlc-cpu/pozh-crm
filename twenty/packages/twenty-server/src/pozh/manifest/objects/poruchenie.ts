// пожсервис: объект «Поручение с совещания» — то, что языковая модель вытащила
// из разговора и что человек ещё не подтвердил.
//
// ПОЧЕМУ СВОЙ ОБЪЕКТ, А НЕ ВСТРОЕННАЯ ЗАДАЧА TWENTY. Соседний файл
// naryad-s-doski.ts решает похожий вопрос ровно наоборот — наряд с доски
// заводится встроенной задачей, а не своим объектом, — и объясняет почему: на
// встроенной задаче держатся подборки «Горит на этой неделе» и «Просрочено».
// Здесь мы поступаем иначе, и вот в чём разница.
//
// Наряд с доски — это УЖЕ задача: её завёл человек, он за неё отвечает, срок
// настоящий. Поручение с совещания до утверждения — ЧЕРНОВИК, который вытащила
// из разговора программа. Часть таких черновиков окажется мусором: модель может
// принять обсуждение за поручение или приписать дело не тому человеку.
//
// Заведи мы их сразу встроенными задачами — этот мусор попал бы прямиком в
// «Горит на этой неделе» и «Просрочено», то есть ровно в те два списка, по
// которым в компании смотрят, что горит. Один день с непроверенными
// черновиками — и людям этим спискам больше верить нельзя.
//
// Поэтому: черновик живёт здесь, отдельно, и в подборки сроков не попадает.
// После утверждения он уезжает задачей на доску, а оттуда обычным часовым
// обменом приезжает обратно встроенной задачей Twenty — той самой, что попадает
// в подборки. То есть правило «сроки держатся на встроенной задаче» не
// нарушено: просто задача заводится на шаг позже, когда человек уже сказал «да».
//
// ЧТО ЗДЕСЬ ЕСТЬ, ЧЕГО НЕТ У ОБЫЧНОЙ ЗАДАЧИ. Цитата из расшифровки и отметка,
// что она в расшифровке действительно нашлась. Это и есть способ проверять
// модель: человек читает строку «Сидоров — проверить путевой лист перед
// выездом», смотрит на цитату рядом и за пять секунд понимает, было такое или
// придумалось. Без цитаты проверка означала бы переслушивание записи, то есть
// не делалась бы никогда.

