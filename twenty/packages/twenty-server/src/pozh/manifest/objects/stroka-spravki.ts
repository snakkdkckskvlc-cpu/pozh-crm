// пожсервис: объект «Строка справки» — одна позиция к списанию.
//
// ЗАЧЕМ. Это самое живое место всего показа 26.08.2026. Программа берёт строку
// справки, ищет похожее в остатках объекта и говорит человеку: «вот есть такой
// кабель, очень похож, совпадение 100%. Его хотите списать? 97 метров,
// числится 310, другими строками не зарезервировано, свободно будет 213».
// Ровно эти числа здесь и лежат.
//
// ПОЧЕМУ ПРОЦЕНТ СОВПАДЕНИЯ ХРАНИТСЯ, А НЕ СЧИТАЕТСЯ КАЖДЫЙ РАЗ. Он посчитан
// в тот момент, когда человек принимал решение, и именно его человек видел.
// Пересчитанный завтра — по изменившимся остаткам — покажет другое число, и
// разобраться, почему согласились на 63%, будет уже нельзя. На показе как раз
// такой случай и разбирали: заглушка совпала на 63%, и подтверждал её человек.
//
// ЧЕГО ПРОГРАММА НЕ ДЕЛАЕТ. Не подтверждает сама. Слова владельца: «эта система
// только подсвечивает все моменты, она ничего не делает за нас... человек всё
// равно в итоге перепроверяет». Поэтому у строки есть состояние, а не
// автоматический переход.

