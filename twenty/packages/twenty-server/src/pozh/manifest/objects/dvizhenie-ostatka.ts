// ЗАЧЕМ. Остаток отвечает на «сколько сейчас», движение — на «почему столько».
// Без движений первый же спор с бухгалтерией упирается в слово против слова.
// На показе 26.08.2026 владелец открывал именно историю: «всю историю по
// объекту видно, по данной конкретной позиции».
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО ОБЪЕКТА: движение появляется только после утверждения.
// Слова владельца дословно: «пока все они там нажимают кнопки, это всё
// черновики. Как только я одобрю — списано». Поэтому у записи есть и признак
// утверждения, и кто утвердил: черновик и утверждённое движение — это не два
// состояния одной кнопки, а разница между «предложено» и «случилось».
//
// ЧИСЛО СО ЗНАКОМ, А НЕ ДВА ПОЛЯ. Приход и списание отличаются знаком, и
// хранить их в двух полях значит каждый раз помнить, какое из них заполнено.
// Сумма движений по позиции должна сходиться с её остатком простым сложением.

