// пожсервис: наряды, приехавшие с доски задач, — обычные задачи Twenty.
//
// ЧТО ЭТО ВООБЩЕ. Доска задач (`~/assistent-pb/apps/doska`) — единственная часть
// системы с выходом в интернет: прораб ведёт с телефона свои наряды, находясь на
// объекте. Раз в час контора сама заходит на доску, забирает изменившееся и
// заводит здесь. Разговор идёт только изнутри наружу, ни одного открытого входа
// в офисной сети при этом нет.
//
// ПОЧЕМУ НЕ СВОЙ ОБЪЕКТ «НАРЯД». Первым делом хотелось завести пятнадцатый
// объект рядом с остальными. Не надо, и вот почему.
//
// Задача в Twenty уже есть, она встроенная, и на ней держится всё остальное:
// подборки «Горит на этой неделе» и «Просрочено» (см. pozh-vidy-zadach.ts)
// построены на её сроке и состоянии, список дел цепляется к ней же
// (svyaz-s-zadachej.ts), она показывается на карточке контрагента и ищется
// общим поиском. Свой объект «Наряд» получил бы вместо всего этого пустую
// таблицу — и наряд с телефона не попал бы ни в одну подборку сроков. То есть
// главный смысл переноса — «чтобы контора видела горящее» — пропал бы вместе с
// ним.
//
// Поэтому наряд с доски — это задача Twenty, а здесь описано ровно одно: откуда
// она приехала.
//
// ЗАЧЕМ ДВА ПОЛЯ И УКАЗАТЕЛЬ. Обмен идёт повторами: приёмник ходит на доску раз
// в час и приносит всё, что изменилось. Один и тот же наряд приезжает много раз
// — сегодня завели, завтра поправили срок, послезавтра дописали реплику. Без
// признака «это тот же самый» контора получала бы новую задачу на каждый заход,
// и через неделю в списке лежало бы сорок «Заменить огнетушители».
//
// Пара «откуда приехало» + «номер там» — тот же приём, которым в этой описи
// держится от задвоения перенос из старой базы (pozh-ukazateli.ts). Проверка
// «а нет ли уже такой» на стороне приёмника его не заменяет: два обмена,
// запущенные одновременно, оба ответят «нет» и оба запишут.

import { getIndexUniversalIdentifier, type IndexManifest } from 'twenty-shared/application';
import { type ObjectFieldManifest } from 'twenty-shared/application';

import { ПРИЛОЖЕНИЕ } from 'src/pozh/manifest/pozh-ids';
import { опознаватель, текст } from 'src/pozh/manifest/pozh-pole';

/**
 * Встроенная задача Twenty. Опознаватель постоянный и взят из работающей
 * системы — тот же, что в pozh-vidy-zadach.ts и svyaz-s-zadachej.ts.
 *
 * Повторён здесь, а не вынесен в общее место, намеренно: три места, где он
 * нужен, — это три разных повода, и вынесенное «общее» первым же переносом
 * файла превратится в загадку «почему задача знает про доску».
 */
const ЗАДАЧА = '20202020-1ba1-48ba-bc83-ef7e5990ed10';

/**
 * Как приёмник подписывает приехавшее. Значение записано здесь и в приёмнике
 * (`priyomnik.py`), и разойтись им нельзя: разойдутся — задачи начнут
 * задваиваться, потому что пара «источник + номер» перестанет совпадать со
 * старой.
 */
export const ИСТОЧНИК_ДОСКА = 'доска';

// Поля добавляются ВСТРОЕННОМУ объекту, и это работает: каждое поле знает, кому
// принадлежит, а к встроенным объектам описанием привязываться можно — тем же
// способом к задаче цепляется список дел.
//
// «Правит человек: нет» у обоих. Поправленное руками поле «откуда приехало»
// означает, что следующий обмен заведёт наряд заново, — а понять это по экрану
// невозможно.
export const поляНарядаСДоски: ObjectFieldManifest[] = [
  текст({
    объект: ЗАДАЧА,
    имя: 'sourceSystem',
    подпись: 'Система-источник',
    пояснение:
      'Откуда приехала задача. У наряда с доски здесь «доска», '
      + 'у заведённых в CRM руками — пусто, и так и надо.',
    правитЧеловек: false,
  }),
  текст({
    объект: ЗАДАЧА,
    имя: 'sourceId',
    подпись: 'Номер в источнике',
    пояснение: 'Номер наряда на доске задач. По нему обмен узнаёт задачу и не заводит вторую.',
    правитЧеловек: false,
  }),
];

/**
 * Уникальна ПАРА, а не каждое поле по отдельности.
 *
 * Оба поля необязательны намеренно — ровно по той причине, что расписана в
 * `pozh-pole.ts::источник`: при значении по умолчанию «пустая строка» все
 * заведённые руками задачи оказались бы повторами друг друга, и вторая просто
 * не записалась бы. Молча. База считает «пусто» несравнимым даже с другим
 * «пусто», поэтому руками можно заводить сколько угодно задач, а у приехавших с
 * доски пара своя у каждой.
 */
export const указательНарядаСДоски: IndexManifest = {
  universalIdentifier: getIndexUniversalIdentifier({
    applicationUniversalIdentifier: ПРИЛОЖЕНИЕ,
    objectUniversalIdentifier: ЗАДАЧА,
    name: 'sourceUnique',
  }),
  objectUniversalIdentifier: ЗАДАЧА,
  isUnique: true,
  fields: ['sourceSystem', 'sourceId'].map((поле) => ({
    universalIdentifier: getIndexUniversalIdentifier({
      applicationUniversalIdentifier: ПРИЛОЖЕНИЕ,
      objectUniversalIdentifier: ЗАДАЧА,
      name: `sourceUnique:${поле}`,
    }),
    fieldUniversalIdentifier: опознаватель(ЗАДАЧА, поле),
  })),
};
