/**
 * Связь «огнетушитель → договор обслуживания». Описана здесь, а не в файле
 * договора, потому что решение «что делать при удалении» принимается со стороны
 * огнетушителя: это его судьба решается.
 *
 * ОБЕ половины описываются разом (иначе выкладка падает), но раскладываются по
 * разным объектам: ссылка — сюда, обратный список — в договор.
 *
 * ПРИ УДАЛЕНИИ — ОБНУЛИТЬ, и это осознанный выбор из трёх:
 *
 * - «по цепочке» (значение Twenty ПО УМОЛЧАНИЮ, если не указать ничего) удалило
 *   бы огнетушители вместе с договором. Это худшее, что может случиться: баллоны
 *   останутся висеть на стене, а мы про них забудем и пропустим срок перезарядки.
 * - «запретить» не даст удалить договор, пока к нему привязан хоть один баллон.
 *   Звучит безопасно, но упирается в жизнь: договор кончается и заключается
 *   заново каждый год, а огнетушитель тот же самый. Ошибочно заведённый договор
 *   пришлось бы расцеплять руками по всему списку.
 * - «обнулить» оставляет огнетушитель со всей его историей проверок, просто без
 *   договора. Чей он — не теряется: у огнетушителя есть своя ссылка на
 *   организацию, и та стоит на «запретить».
 */
