// пожсервис: объект «Счётчик номеров путевых листов».
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ОБЪЕКТ РАДИ ДВУХ ПОЛЕЙ. Номер листа нельзя брать как
// «максимум из выписанных»: удалили или аннулировали последнюю пачку — и
// максимум откатился назад, а номера пошли по второму кругу. Это уже ловилось
// тестом в старом приложении. Счётчик хранит последний выданный номер отдельно
// и только растёт, независимо от того, что случилось с самими листами.
//
// Самовозрастающего номера среди типов полей Twenty нет вовсе — проверено по
// перечню типов. Значит счётчик наш, и увеличивает его служба документов в
// момент выписки.
//
// ДВОЙНАЯ ЗАЩИТА, И ЭТО НЕ ПЕРЕСТРАХОВКА. Если два человека выпишут лист
// одновременно и счётчик отдаст один номер дважды, второму откажет база —
// «Номер» у путевого листа уникален. Служба переспросит счётчик. То есть за
// «только растёт» отвечает счётчик, а за «не повторяется» — база; ни одно из
// двух правил не держится на одной лишь аккуратности кода.
//
// Разбор — docs/russian-business/SCHEMA_PLAN.md, §8б и решение 2.

import { type ObjectManifest } from 'twenty-shared/application';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { опознаватель, текст, число } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.счётчикНомеров;

export const счётчикНомеров: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhNumberCounter',
  namePlural: 'pozhNumberCounters',
  labelSingular: 'Счётчик номеров',
  labelPlural: 'Счётчики номеров',
  description:
    'Последний выданный номер путевого листа. Только растёт: удалённая пачка не отдаёт свои номера повторно.',
  icon: 'IconHash',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'counterKey'),
  fields: [
    // Ключ — это то, в каких границах нумерация сквозная: «2026» или
    // «2026-ПожСервис», если организации нумеруются порознь. Уникальность
    // держит база: два счётчика на один ключ — это два ряда номеров и
    // гарантированный повтор.
    //
    // Обязательным ключ при этом не сделать: уникальность и обязательность в
    // одном поле база не совмещает (обязательность требует значения по
    // умолчанию, а уникальность его запрещает). Здесь уникальность важнее —
    // пустой ключ поймает служба, повторяющиеся номера не поймает никто.
    текст({
      объект: О,
      имя: 'counterKey',
      подпись: 'Ключ счётчика',
      пояснение: 'В каких границах нумерация сквозная: «2026» либо «2026-ПожСервис».',
      обязательно: true,
      уникально: true,
    }),
    // Ноль по умолчанию — правильное начальное состояние: «не выдано ещё ни
    // одного номера», первый выданный будет 1. Пустое значение здесь означало
    // бы «неизвестно, докуда дошли», а это ровно то, чего счётчик не должен
    // допускать.
    число({
      объект: О,
      имя: 'lastIssuedNumber',
      подпись: 'Последний выданный номер',
      пояснение: 'Увеличивает служба документов при выписке. Назад не откатывается никогда.',
      обязательно: true,
    }),
  ],
};
