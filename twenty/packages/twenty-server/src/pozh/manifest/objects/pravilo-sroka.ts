// пожсервис: объект «Правило срока» — настройка того, о чём и за сколько дней
// предупреждать.
//
// Разбор с полями и почему они такие — docs/russian-business/SCHEMA_PLAN.md, §11.
//
// Что это такое. Одна запись — одно правило вида «смотри на поле "Следующая
// проверка" у огнетушителей и за 14 дней до неё поставь задачу». Правил будет
// много и заводить их будут люди, поэтому это записи в таблице, а не строчки в
// коде: добавить срок должен уметь секретарь, а не программист.
//
// Чего этот объект НЕ делает: он ничего не проверяет сам. Он только хранит
// настройку; обходит записи и создаёт предупреждения служба документов по
// расписанию.

import { type ObjectManifest } from 'twenty-shared/application';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { выбор, опознаватель, текст, флажок, число } from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.правилоСрока;

// Что делать, когда срок подошёл. Значения списка выбора Twenty требует
// ЗАГЛАВНЫМИ с подчёркиваниями, человек видит подпись.
const действия = [
  { value: 'NOTIFY', label: 'Предупредить', color: 'sky' },
  { value: 'TASK', label: 'Задача', color: 'purple' },
  { value: 'EMAIL', label: 'Письмо', color: 'orange' },
];

export const правилоСрока: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhDeadlineRule',
  namePlural: 'pozhDeadlineRules',
  labelSingular: 'Правило срока',
  labelPlural: 'Правила сроков',
  description: 'Настройка предупреждений: за каким полем-датой следить и за сколько дней предупредить.',
  icon: 'IconAlarm',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'name'),
  fields: [
    // Заголовок записи. Уникальным не делаем: два похожих правила с одним
    // названием — беспорядок, но не поломка, а вот запрет завести второе
    // правило «Перезарядка» для другого справочника мешал бы работать.
    // Заполненность держит служба документов (правило 3: база в Twenty умеет
    // гарантировать только «что-то лежит», а не «человек заполнил»).
    текст({
      объект: О,
      имя: 'name',
      подпись: 'Название',
      пояснение: 'Как правило называется для человека: «Перезарядка огнетушителей за 14 дней».',
    }),
    // «Справочник» и «Поле-дата» — ТЕКСТ, а не ссылки на описание объектов и
    // полей, и это вынужденно: описание объектов лежит в другой схеме базы
    // (`core`), а записи — в схеме рабочей области, сослаться из одной в другую
    // нельзя (проверено).
    //
    // Цена этого решения известна заранее: переименовали поле — правило молча
    // перестало срабатывать, никакой ошибки не будет. Поэтому перечень
    // действующих правил сверяется с перечнем полей после каждого обновления
    // Twenty; это уже стоит в контрольном списке обновления.
    //
    // Значение по умолчанию — пустая строка: правило без справочника
    // бессмысленно, но база проверить это не умеет, проверяет служба.
    текст({
      объект: О,
      имя: 'objectName',
      подпись: 'Справочник',
      пояснение: 'Техническое имя объекта, за которым следим: pozhFireExtinguisher, pozhServiceContract.',
      обязательно: true,
    }),
    текст({
      объект: О,
      имя: 'dateFieldName',
      подпись: 'Поле-дата',
      пояснение: 'Техническое имя поля-даты в этом справочнике: nextInspectionOn, validTo.',
      обязательно: true,
    }),
    // Ноль означает «в самый день срока», а не «не заполнено». Отличить одно от
    // другого база не может (правило 3), поэтому смысл нуля записан здесь.
    число({
      объект: О,
      имя: 'daysBefore',
      подпись: 'За сколько дней',
      пояснение: 'За сколько дней до даты предупреждать. Ноль — в сам день срока.',
      обязательно: true,
    }),
    // По умолчанию — самое тихое действие. Правило, которое по умолчанию само
    // рассылает письма заказчикам, — это разосланные по недосмотру письма.
    выбор({
      объект: О,
      имя: 'action',
      подпись: 'Что делать',
      пояснение: 'Предупредить — только показать у нас; задача — завести дело; письмо — отправить наружу.',
      варианты: действия,
      поумолчанию: 'NOTIFY',
    }),
    // Выключение вместо удаления. Удалённое правило уносит с собой ответ на
    // вопрос «а почему мы вообще про это предупреждали» — через год этого никто
    // не вспомнит. Выключенное лежит рядом и объясняет само себя.
    флажок({
      объект: О,
      имя: 'isEnabled',
      подпись: 'Включено',
      пояснение: 'Снятая галочка заменяет удаление: правило перестаёт срабатывать, но остаётся видно.',
      поумолчанию: true,
    }),
    // Пары «Система-источник · Идентификатор в источнике» здесь намеренно нет:
    // правила сроков не переносятся из старой базы, их там не было — заводить
    // будем руками. Так же поступили с другими нашими служебными объектами
    // (связка прицепов, счётчик номеров), у них этой пары тоже нет.
  ],
};
