// пожсервис: объект «Позиция заявки» — то, что снабженец вытащил из заявки.
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ ЗАЯВКИ. Прораб пишет «просто кабель», а снабженец
// расшифровывает это в «кабель силовой алюминиевый такой-то, 200 м, закупка».
// Слова владельца 26.08.2026: «она понимает, что это такое, и она здесь это
// дело расшифровывает». Заявка — это просьба целиком, позиция — одна
// разобранная строка. Разбор одной строки не должен трогать остальные.
//
// ДВА ПОЛЯ ПОД НАИМЕНОВАНИЕ, А НЕ ОДНО. `askedAs` — как попросили, `name` — как
// разобрали. Затирать первое вторым нельзя: если разобрали неверно, вернуться
// будет не к чему, а спор с прорабом «я не это просил» решается только исходной
// формулировкой.
//
// ТИП МАТЕРИАЛА. «У нас есть закупка, давальческий материал — для нас важно
// поделить, а остальное по мелочи». Деление важно потому, что списываются они
// по разным справкам: давальческий по 304, закупка по 190.

