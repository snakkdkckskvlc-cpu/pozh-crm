// пожсервис: объект «Совещание» — карточка ежедневной планёрки с её расшифровкой.
//
// ОТКУДА ЭТО ВЗЯЛОСЬ. Совещания в компании проходят каждый день и пишутся на
// диктофон, запись ложится на Яндекс.Диск. Дальше её не слушает никто: чтобы
// вспомнить, что поручили Иванову во вторник, надо переслушать час звука. То
// есть запись есть, а толку от неё нет.
//
// Задача карточки — превратить час звука в две вещи, которые можно прочитать за
// минуту: текст разговора и список поручений с исполнителями и сроками.
//
// КАК ЗАПОЛНЯЕТСЯ. Руками — почти никак, и это главное свойство. Записи
// забирает с диска отдельная маленькая программа по расписанию, расшифровывает
// служба документов, поручения вытаскивает из текста языковая модель. Человек
// делает ровно одно действие: читает и ставит состояние «Утверждено». После
// этого поручения разъезжаются людям задачами на доску.
//
// Поэтому у большинства полей стоит «правитЧеловек: false»: их кладёт
// программа, и правка руками означала бы, что карточка разошлась с записью.
// Правятся только название и — при необходимости — сама расшифровка.
//
// ЧТО СЮДА НЕ КЛАДЁТСЯ. Сам звук. Запись остаётся на Яндекс.Диске, у нас лежит
// только ссылка на неё. Второй экземпляр часового звука на каждый рабочий день
// — это гигабайты в месяц ради того, что уже хранится в другом месте.
//
// ПРО СРОК ХРАНЕНИЯ. Карточка живёт месяц, потом убирается сама (решение
// владельца: «прошлые совещания хранятся в архиве месяц»). Чистку делает служба
// документов тем же способом, каким убирает старые загруженные документы. Ссылка
// на диск при этом никуда не девается — запись переживает карточку.
//
// КТО ЭТО ВИДИТ. Все. Разграничения прав в CRM пока нет вовсе, и владелец,
// выбирая место для расшифровки, знал об этом: решение от 20.08.2026 — карточка
// живёт в CRM и видна всем тридцати сотрудникам. Если однажды понадобится
// закрыть часть совещаний от части людей, это будет не правка полей, а
// разграничение доступа целиком, и делать его надо будет заранее.

import { type ObjectManifest } from 'twenty-shared/application';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import {
  выбор,
  дата,
  датаВремя,
  источник,
  опознаватель,
  текст,
  число,
} from 'src/pozh/manifest/pozh-pole';

const О = ОБЪЕКТЫ.совещание;

// Состояния карточки. Это НЕ украшение списка: по ним работает вся цепочка, и
// каждое состояние означает «чей сейчас ход».
//
// В_ОЧЕРЕДИ    — запись нашли на диске, но ещё не расшифровывали. Ход программы.
// РАСШИФРОВКА  — служба документов занята этой записью прямо сейчас. Ход программы.
// НА_ПРОВЕРКЕ  — текст и поручения готовы. ХОД ЧЕЛОВЕКА, и это единственное
//                состояние, в котором от него что-то требуется.
// УТВЕРЖДЕНО   — человек прочитал и согласился. Раздатчик увидит это и разошлёт
//                поручения на доску задач.
// ОШИБКА       — расшифровать не удалось. Причина в поле «Что пошло не так».
//
// Значения из списка можно добавлять, но нельзя удалять: при перестройке списка
// записи с исчезнувшим значением теряют его молча (правило 9 плана схемы).
//
// ПОЧЕМУ УТВЕРЖДЕНИЕ — ЭТО СМЕНА СОСТОЯНИЯ, А НЕ КНОПКА. Своей кнопки на
// карточке Twenty нарисовать не даёт, а заводить ради неё отдельный экран
// означало бы нарушить правило владельца «всё новое делается в CRM». Выпадающий
// список состояния делает ровно то же самое: человек выбирает «Утверждено», и
// цепочка идёт дальше. Разница только в том, как это выглядит.
const состоянияСовещания = [
  { value: 'QUEUED', label: 'В очереди', color: 'gray' },
  { value: 'TRANSCRIBING', label: 'Расшифровывается', color: 'blue' },
  { value: 'REVIEW', label: 'На проверке', color: 'yellow' },
  { value: 'APPROVED', label: 'Утверждено', color: 'green' },
  { value: 'FAILED', label: 'Ошибка', color: 'red' },
];

export const совещание: ObjectManifest = {
  universalIdentifier: О,
  nameSingular: 'pozhMeeting',
  namePlural: 'pozhMeetings',
  labelSingular: 'Совещание',
  labelPlural: 'Совещания',
  description:
    'Ежедневная планёрка: расшифровка записи с Яндекс.Диска и поручения, вытащенные из разговора. Утверждение раздаёт поручения задачами на доску.',
  icon: 'IconMicrophone',
  labelIdentifierFieldMetadataUniversalIdentifier: опознаватель(О, 'title'),
  fields: [
    // Название — то, по чему совещание ищут списком. Программа ставит его сама
    // из даты («Планёрка 20.08»), но правится руками: настоящее название
    // («Разбор по третьему цеху») человек знает, а программа нет.
    текст({
      объект: О,
      имя: 'title',
      подпись: 'Название',
      пояснение: 'Ставится программой из даты. Правьте, если у совещания было своё название.',
    }),
    дата({
      объект: О,
      имя: 'heldOn',
      подпись: 'Когда прошло',
      пояснение: 'Берётся из даты файла записи, а не из дня, когда её расшифровали.',
    }),
    // ССЫЛКА НА ЗАПИСЬ — то самое поле, которое просил владелец: «поле куда
    // добавляется ссылка на диск откуда берется запись».
    //
    // Работает в обе стороны. Обычно её заполняет программа, забравшая файл с
    // диска. Но человек может вписать ссылку и руками — тогда программа заберёт
    // именно эту запись, даже если она лежит не в той папке, за которой следят.
    // Так разбирают разовое совещание, записанное не по расписанию.
    текст({
      объект: О,
      имя: 'diskLink',
      подпись: 'Ссылка на запись',
      пояснение:
        'Адрес записи на Яндекс.Диске. Обычно проставляется сам. Можно вписать руками — тогда программа заберёт именно её.',
    }),
    // Имя файла на диске. Нужно не человеку, а программе: по нему приёмник
    // отличает «эту запись мы уже брали» от новой. Ссылка для этого не годится
    // — она у Яндекс.Диска бывает временной и меняется между заходами.
    //
    // Уникальность ставим: две карточки на один файл — это два комплекта
    // поручений на одно совещание, то есть задвоенная работа у тридцати человек.
    // Ровно тем же приёмом держится от задвоения перенос нарядов с доски.
    текст({
      объект: О,
      имя: 'sourceFile',
      подпись: 'Файл записи',
      пояснение: 'Имя файла на диске. По нему программа понимает, что эту запись уже брали.',
      уникально: true,
      правитЧеловек: false,
    }),
    выбор({
      объект: О,
      имя: 'state',
      подпись: 'Состояние',
      пояснение:
        'Поставьте «Утверждено», когда прочитали расшифровку и согласны с поручениями — после этого они разъедутся людям на доску задач.',
      варианты: состоянияСовещания,
      поумолчанию: 'QUEUED',
    }),
    // РАСШИФРОВКА целиком. Правится: распознавание речи ошибается в фамилиях и
    // в редких словах, и поправить строку должно быть можно.
    //
    // Но править её обычно НЕ НАДО, и это стоит сказать прямо. Человек проверяет
    // не текст, а поручения — их полтора десятка строк против двадцати страниц
    // разговора. Расшифровка здесь для того, чтобы можно было свериться с
    // первоисточником, а не для вычитки.
    текст({
      объект: О,
      имя: 'transcript',
      подпись: 'Расшифровка',
      пояснение:
        'Текст разговора целиком. Проверять его весь не нужно — сверяйтесь по нему, когда поручение вызывает сомнение.',
    }),
    // «И ВСЁ ЧТО К НЕМУ ОТНОСИЛОСЬ» — прямая просьба владельца, и это не то же
    // самое, что список поручений.
    //
    // Половина сказанного про человека поручением не является: «у Ковалёва
    // отпуск с двадцать пятого, а он единственный сертифицирован по автоматике»
    // — это не задача, но Ковалёву и кадровику это знать надо. Такое сюда и
    // складывается: по строке на человека, коротко, о чём при нём шла речь.
    //
    // Почему одним полем, а не отдельными записями на каждого. Читают это ровно
    // один раз — в день совещания, и читают целиком. Список записей, который
    // всегда открывают целиком, — это таблица там, где хватает абзаца.
    текст({
      объект: О,
      имя: 'perPerson',
      подпись: 'Кого что касается',
      пояснение: 'По строке на человека: о чём при нём шла речь, кроме самих поручений.',
      правитЧеловек: false,
    }),
    число({
      объект: О,
      имя: 'durationMinutes',
      подпись: 'Длительность записи, минут',
      пояснение: 'Сколько шла запись. Нужно, чтобы видеть, почему расшифровка идёт долго.',
    }),
    датаВремя({
      объект: О,
      имя: 'approvedAt',
      подпись: 'Когда утверждено',
      пояснение: 'Ставится само при переводе в «Утверждено».',
    }),
    // ЗАЩИТА ОТ ПОВТОРНОЙ РАЗДАЧИ. Раздатчик ходит по расписанию и берёт все
    // утверждённые совещания. Без отметки «уже роздано» он на каждом заходе
    // заводил бы те же задачи заново, и через сутки у человека висело бы
    // двадцать четыре одинаковых поручения.
    //
    // Отметка стоит здесь, а не на каждом поручении, потому что раздача — одно
    // действие на совещание целиком: либо разошлось всё, либо ничего.
    датаВремя({
      объект: О,
      имя: 'handedOutAt',
      подпись: 'Когда розданы поручения',
      пояснение: 'Ставит раздатчик. Пока пусто — поручения на доску ещё не уехали.',
      правитЧеловек: false,
    }),
    // Текст отказа для ЧЕЛОВЕКА, а не для программиста: «файл не открылся, он
    // не похож на запись звука», а не «UnsupportedCodec». Читать это будет
    // секретарь, и по прочитанному он должен понять, что делать дальше.
    текст({
      объект: О,
      имя: 'errorText',
      подпись: 'Что пошло не так',
      пояснение: 'Заполняется, только если расшифровать не удалось.',
      правитЧеловек: false,
    }),
    ...источник(О),
  ],
};
