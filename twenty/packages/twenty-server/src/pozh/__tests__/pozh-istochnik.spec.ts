// пожсервис: замок на поломку, из-за которой нельзя было завести вторую запись.
//
// ЧТО БЫЛО. У полей «Система-источник» и «Идентификатор в источнике» стояло
// значение по умолчанию — пустая строка. Пара этих полей уникальна: она держит
// перевозку из старой базы от задвоения. Но у ВСЕХ записей, заведённых руками,
// пара получалась одна и та же («пусто», «пусто») — и вторая такая запись
// сталкивалась с первой.
//
// ЧЕМ ЭТО БЫЛО ПЛОХО ОСОБЕННО. Отказ был молчаливый: в браузере первый
// контрагент завёлся, второй просто не появился. Ни строки об ошибке, счётчик
// остался «1». Нашлось только живым обходом — заведением двух записей подряд.
//
// ПОЧЕМУ ПУСТО РАБОТАЕТ, А ПУСТАЯ СТРОКА НЕТ. База считает «пусто» несравнимым
// даже с другим «пусто», поэтому руками можно завести сколько угодно записей.
// А пустая строка — обычное значение, и второе такое же считается повтором.

import { манифестПожСервиса } from 'src/pozh/manifest/pozh-manifest';

const ПОЛЯ_ИСТОЧНИКА = ['sourceSystem', 'sourceId'];

describe('поля «откуда приехала запись»', () => {
  const все = манифестПожСервиса.objects.flatMap((о) =>
    о.fields
      .filter((п) => ПОЛЯ_ИСТОЧНИКА.includes(п.name))
      .map((п) => ({ объект: о.nameSingular, поле: п })),
  );

  it('вообще нашлись', () => {
    // Без этого проверка молча проходила бы на пустом списке — та же болезнь,
    // от которой она заведена.
    expect(все.length).toBeGreaterThanOrEqual(ПОЛЯ_ИСТОЧНИКА.length * 10);
  });

  it('не имеют значения по умолчанию', () => {
    const свалившиеся = все
      .filter(({ поле }) => 'defaultValue' in поле && поле.defaultValue !== undefined)
      .map(({ объект, поле }) => `${объект}.${поле.name}`);

    expect(свалившиеся).toEqual([]);
  });

  it('разрешают пустоту', () => {
    const свалившиеся = все
      .filter(({ поле }) => (поле as { isNullable?: boolean }).isNullable !== true)
      .map(({ объект, поле }) => `${объект}.${поле.name}`);

    expect(свалившиеся).toEqual([]);
  });
});
