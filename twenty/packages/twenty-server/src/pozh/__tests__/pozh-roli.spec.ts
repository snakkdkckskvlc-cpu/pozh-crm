// пожсервис: что каждая должность видит и — главное — чего НЕ видит.
//
// ПОЧЕМУ ПРОВЕРКА НАПИСАНА В ОБЕ СТОРОНЫ. В карте работ разграничение доступа
// стоит самым опасным местом плана по одной причине: ошибка здесь не видна на
// глаз. Сломанная кнопка заметна сразу, а лишний открытый раздел человек
// видит, считает, что так и надо, и молчит. Проверка «бухгалтер видит машины»
// зеленеет и на раскладке «всем всё» — поэтому рядом обязательна вторая:
// «бухгалтер НЕ видит персональные данные».
//
// Ожидания записаны руками, а не выведены из того же кода: проверка,
// посчитанная тем же способом, что и проверяемое, сходится всегда.

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { КОД_ДОЛЖНОСТИ, роли } from 'src/pozh/manifest/pozh-roli';

const поНазванию = (название: string) => {
  const роль = роли.find((р) => р.label === название);

  if (!роль) {
    throw new Error(`нет должности «${название}»`);
  }

  return роль;
};

/** Видит ли должность записи этого вида. Запрет — это строка в objectPermissions. */
const видит = (название: string, объект: string): boolean => {
  const роль = поНазванию(название);
  const запрет = (роль.objectPermissions ?? []).find(
    (п) => п.objectUniversalIdentifier === объект,
  );

  return запрет?.canReadObjectRecords !== false;
};

describe('должности ПожСервиса', () => {
  it('у каждой должности своё название и свой опознаватель', () => {
    const названия = роли.map((р) => р.label);
    const опознаватели = роли.map((р) => р.universalIdentifier);

    expect(new Set(названия).size).toBe(роли.length);
    expect(new Set(опознаватели).size).toBe(роли.length);
  });

  it('запреты не затирают друг друга', () => {
    // Запретов больше сотни: одиннадцать должностей на семнадцать видов
    // записей. Совпавший опознаватель означал бы, что один запрет молча
    // заменяет другой, и кто-то увидит лишнее.
    const все = роли.flatMap((р) =>
      (р.objectPermissions ?? []).map((п) => п.universalIdentifier),
    );

    expect(new Set(все).size).toBe(все.length);
    expect(все.length).toBeGreaterThan(50);
  });

  it('коды должностей есть у всех и не повторяются', () => {
    // По коду служба документов понимает, какие ЭКРАНЫ показать. Нет кода —
    // должность до экранов не доедет; два одинаковых — доедет чужая.
    const коды = Object.values(КОД_ДОЛЖНОСТИ);

    expect(коды.length).toBe(роли.length - 1); // без должности по умолчанию
    expect(new Set(коды).size).toBe(коды.length);
    expect(коды).not.toContain('');
  });

  // --- Персональные данные: главная граница ---

  it.each(['Кадры', 'Руководитель', 'Бухгалтер и кадры', 'Секретарь и путевые листы'])(
    '%s видит персональные данные водителей',
    (должность) => {
      expect(видит(должность, ОБЪЕКТЫ.данныеВодителя)).toBe(true);
    },
  );

  it.each([
    'Сотрудник ПожСервиса',
    'Секретарь',
    'Инженер',
    'Бухгалтер',
    'Механик',
    'Снабжение',
    'Механик и снабжение',
    'Инженер и снабжение',
    'ПТО',
  ])('%s НЕ видит персональные данные водителей', (должность) => {
    expect(видит(должность, ОБЪЕКТЫ.данныеВодителя)).toBe(false);
  });

  // --- Договоры: тексты с НЛМК ---

  // Кадры и снабжение добавлены разметкой владельца 03.09.2026: кадровику
  // договоры нужны по людям на объектах, снабжению — условия поставки.
  it.each([
    'Секретарь',
    'Инженер',
    'Бухгалтер',
    'Руководитель',
    'Кадры',
    'Снабжение',
    'Бухгалтер и кадры',
    'Секретарь и путевые листы',
    'Инженер и снабжение',
    'ПТО',
  ])(
    '%s видит договоры',
    (должность) => {
      expect(видит(должность, ОБЪЕКТЫ.договор)).toBe(true);
    },
  );

  it.each(['Механик', 'Механик и снабжение', 'Сотрудник ПожСервиса'])(
    '%s НЕ видит договоры',
    (должность) => {
      expect(видит(должность, ОБЪЕКТЫ.договор)).toBe(false);
    },
  );

  // --- Транспорт и путевые листы ---

  it('транспорт у секретаря, а не у механика', () => {
    // Разметка владельца на распечатке 03.09.2026: путевой лист выписывает
    // секретарь, поэтому машины, рейсы и листы отданы ему, а у механика
    // зачёркнуты целиком.
    expect(видит('Секретарь', ОБЪЕКТЫ.машина)).toBe(true);
    expect(видит('Секретарь', ОБЪЕКТЫ.путевойЛист)).toBe(true);
    expect(видит('Механик', ОБЪЕКТЫ.машина)).toBe(false);
    expect(видит('Механик', ОБЪЕКТЫ.путевойЛист)).toBe(false);
  });

  it('секретарь ведёт листы, но реквизиты водителя видит только с ними', () => {
    // Единственное, чем «Секретарь и путевые листы» отличается от секретаря
    // после того, как транспорт отдали обоим: СНИЛС и номера удостоверений.
    expect(видит('Секретарь', ОБЪЕКТЫ.данныеВодителя)).toBe(false);
    expect(видит('Секретарь и путевые листы', ОБЪЕКТЫ.данныеВодителя)).toBe(true);
  });

  it('у механика осталось столько же, сколько у человека без должности', () => {
    // Следствие разметки, которое надо держать на виду: должность есть, а
    // работы за ней нет. Вопрос вынесен владельцу, проверка держит размеченное.
    for (const объект of [ОБЪЕКТЫ.машина, ОБЪЕКТЫ.рейс, ОБЪЕКТЫ.путевойЛист, ОБЪЕКТЫ.договор]) {
      expect(видит('Механик', объект)).toBe(false);
      expect(видит('Механик и снабжение', объект)).toBe(false);
    }
    expect(видит('Механик', ОБЪЕКТЫ.контрагент)).toBe(true);
  });

  it('совмещённые должности перестали быть суммой — и это решение, а не описка', () => {
    // Бухгалтеру транспорт оставлен, бухгалтеру с кадрами — зачёркнут.
    // Проверка стоит затем, чтобы «починка» суммы не вернула его молча.
    expect(видит('Бухгалтер', ОБЪЕКТЫ.машина)).toBe(true);
    expect(видит('Бухгалтер и кадры', ОБЪЕКТЫ.машина)).toBe(false);
    // Снабжению договоры даны, «механику и снабжению» — нет: «только вопрос по
    // документу из юридической проверки», указание владельца.
    expect(видит('Снабжение', ОБЪЕКТЫ.договор)).toBe(true);
    expect(видит('Механик и снабжение', ОБЪЕКТЫ.договор)).toBe(false);
  });

  it('ПТО заведён и видит договоры', () => {
    // Табель ТОиР живёт в службе документов, своих объектов в CRM у ПТО нет.
    // Здесь ему нужны договоры — сверять акты и закрывающие с условиями.
    expect(видит('ПТО', ОБЪЕКТЫ.договор)).toBe(true);
    expect(видит('ПТО', ОБЪЕКТЫ.данныеВодителя)).toBe(false);
  });

  // --- Крайние случаи ---

  it('руководитель видит все виды записей без исключений', () => {
    for (const объект of Object.values(ОБЪЕКТЫ)) {
      expect(видит('Руководитель', объект)).toBe(true);
    }
  });

  it('должность по умолчанию — самая узкая, но не пустая', () => {
    // Человек, заведённый в пятницу вечером, в понедельник должен что-то
    // видеть. И при этом ничего лишнего: незамеченная дыра хуже отсутствующей
    // защиты — её никто не чинит.
    expect(видит('Сотрудник ПожСервиса', ОБЪЕКТЫ.контрагент)).toBe(true);
    expect(видит('Сотрудник ПожСервиса', ОБЪЕКТЫ.совещание)).toBe(true);
    expect(видит('Сотрудник ПожСервиса', ОБЪЕКТЫ.договор)).toBe(false);
    expect(видит('Сотрудник ПожСервиса', ОБЪЕКТЫ.путевойЛист)).toBe(false);
    expect(видит('Сотрудник ПожСервиса', ОБЪЕКТЫ.данныеВодителя)).toBe(false);
  });

  it('никто, кроме администратора, не удаляет записи', () => {
    // Удалённая запись уезжает в корзину и продолжает занимать своё место:
    // повторная перевозка из старой базы её не восстановит и молча пропустит.
    // Проверено на живой базе.
    for (const роль of роли) {
      expect(роль.canSoftDeleteAllObjectRecords).toBe(false);
      expect(роль.canDestroyAllObjectRecords).toBe(false);
      expect(роль.canUpdateAllSettings).toBe(false);
    }
  });
});
