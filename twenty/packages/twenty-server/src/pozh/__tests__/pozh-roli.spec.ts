// пожсервис: что видит обычный сотрудник, а что — только кадры.
//
// ЗАЧЕМ. Разграничение доступа названо в карте работ самым опасным местом всего
// плана, и по одной причине: ошибка здесь не видна на глаз. Человек просто
// увидит лишнее и промолчит. Такая утечка уже была — список водителей со СНИЛС
// и номерами водительских удостоверений открывался любому сотруднику, закрыто
// 08.08.2026. Здесь замок, чтобы она не вернулась.
//
// ПОЧЕМУ СПИСОК ВИДИМОГО ЗАФИКСИРОВАН ПОИМЁННО, А НЕ ПОСЧИТАН. Роль по
// умолчанию открыта на всё и закрывается исключениями. Значит, каждый новый вид
// записей попадает в неё сам, молча и в тот же день, когда его завели. Счётчик
// этого не ловит: добавили один вид, убрали другой — число прежнее. Поэтому
// ниже лежит поимённый список, и новый вид записей обязан пройти через правку
// ЭТОГО файла — то есть через вопрос «а этот кто его видит?».
//
// ЧЕГО ЭТА ПРОВЕРКА НЕ ДАЁТ. Она читает опись, а не работающую программу.
// Поймает «забыли закрыть» в описи, но не поймает, если сама CRM опись не
// применила. Живая сверка глазами по-прежнему нужна и записана отдельным шагом.

import { ОБЪЕКТЫ, РОЛЬ_КАДРЫ, РОЛЬ_ПО_УМОЛЧАНИЮ } from 'src/pozh/manifest/pozh-ids';
import { манифестПожСервиса } from 'src/pozh/manifest/pozh-manifest';

// Что обычный сотрудник видеть ДОЛЖЕН. Персональных данных водителя здесь нет,
// и это единственное исключение на сегодня.
//
// Восемь записей снабжения (27.08.2026) сюда добавлены сознательно, а не за
// компанию. Вопрос «а этот кто его видит?» по каждой задан и отвечен так:
// снабжением занимается вся цепочка от прораба до бухгалтера, и прятать от
// сотрудника заявки, остатки или справки не от кого — это его же работа.
// Единственное, что в них есть личного, — фамилия прораба в заявке, а фамилии
// сотрудников в CRM и так открыты (водители видны всем). Закрыты по-прежнему
// только СНИЛС и номера водительских удостоверений.
//
// Цены в спецификации и в позициях заявок — коммерческие, но не личные:
// договоры с ценами сотрудник видит и сейчас.
const ВИДИТ_СОТРУДНИК = [
  'pozhChecklistItem',
  'pozhCounterparty',
  'pozhDeadlineRule',
  'pozhDocumentMovement',
  'pozhDriver',
  'pozhFireExtinguisher',
  'pozhMaterialReport',
  'pozhMeeting',
  'pozhMeetingAssignment',
  'pozhNumberCounter',
  'pozhPoint',
  'pozhReportLine',
  'pozhRequest',
  'pozhRequestLine',
  'pozhServiceContract',
  'pozhSite',
  'pozhSpecLine',
  'pozhStockItem',
  'pozhStockMovement',
  'pozhTrailer',
  'pozhTrip',
  'pozhVehicle',
  'pozhWaybill',
  'pozhWaybillTrailer',
];

// Что не видит никто, кроме роли «Кадры».
const ТОЛЬКО_КАДРАМ = ['pozhDriverPersonalData'];

// «Закрыт» здесь означает именно «не прочитает». Запрет на правку при
// разрешённом чтении утечку не останавливает: СНИЛС утекает глазами, а не
// правкой.
const запрещеноЧитать = (право: { canReadObjectRecords?: boolean }) =>
  право.canReadObjectRecords === false;

const роль = (опознаватель: string) => {
  const найдена = манифестПожСервиса.roles.find(
    (р) => р.universalIdentifier === опознаватель,
  );

  if (!найдена) {
    throw new Error(`роль ${опознаватель} пропала из описи`);
  }

  return найдена;
};

// Имя вида записей по опознавателю: в правах стоят опознаватели, а читать
// список отказов удобнее по именам — иначе красная проверка печатает
// шестнадцать одинаковых на вид строк и не говорит ничего.
const имяПоОпознавателю = new Map(
  манифестПожСервиса.objects.map((о) => [о.universalIdentifier, о.nameSingular]),
);

const закрытоДляРоли = (опознавательРоли: string) =>
  (роль(опознавательРоли).objectPermissions ?? [])
    .filter(запрещеноЧитать)
    .map(
      (п) =>
        имяПоОпознавателю.get(п.objectUniversalIdentifier) ??
        п.objectUniversalIdentifier,
    )
    .sort();

describe('кто какие записи видит', () => {
  it('ролей ровно две, и это те самые', () => {
    // Третья роль, заведённая молча, — ровно тот случай, ради которого проверка
    // написана: она ничего не ломает и потому не заметна.
    expect(манифестПожСервиса.roles).toHaveLength(2);
    expect(
      манифестПожСервиса.roles.map((р) => р.universalIdentifier).sort(),
    ).toEqual([РОЛЬ_ПО_УМОЛЧАНИЮ, РОЛЬ_КАДРЫ].sort());
  });

  it('в описи есть все виды записей, перечисленные в этом файле, и ровно они', () => {
    // Без этого проверка молча зеленела бы на урезанном списке — та же болезнь,
    // от которой она заведена. И здесь же ловится новый вид записей: завели —
    // будь добр сказать, кто его видит.
    expect(манифестПожСервиса.objects.map((о) => о.nameSingular).sort()).toEqual(
      [...ВИДИТ_СОТРУДНИК, ...ТОЛЬКО_КАДРАМ].sort(),
    );
  });

  it('обычный сотрудник видит ровно то, что должен, и ничего сверх', () => {
    const закрыто = закрытоДляРоли(РОЛЬ_ПО_УМОЛЧАНИЮ);
    const видит = манифестПожСервиса.objects
      .map((о) => о.nameSingular)
      .filter((имя) => !закрыто.includes(имя))
      .sort();

    expect(закрыто).toEqual([...ТОЛЬКО_КАДРАМ].sort());
    expect(видит).toEqual([...ВИДИТ_СОТРУДНИК].sort());
  });

  it('персональные данные водителя закрыты сотруднику по всем четырём действиям', () => {
    const запрет = (роль(РОЛЬ_ПО_УМОЛЧАНИЮ).objectPermissions ?? []).find(
      (п) => п.objectUniversalIdentifier === ОБЪЕКТЫ.данныеВодителя,
    );

    expect(запрет).toBeDefined();
    // Все четыре, а не только чтение: правка и удаление в обход чтения тоже
    // раскрывают запись — по тому, прошла операция или отказала.
    expect(запрет?.canReadObjectRecords).toBe(false);
    expect(запрет?.canUpdateObjectRecords).toBe(false);
    expect(запрет?.canSoftDeleteObjectRecords).toBe(false);
    expect(запрет?.canDestroyObjectRecords).toBe(false);
  });

  it('кадрам персональные данные водителя открыты', () => {
    // Иначе путевой лист не выписать: СНИЛС и номер удостоверения — его
    // обязательные графы.
    expect(закрытоДляРоли(РОЛЬ_КАДРЫ)).toEqual([]);
  });

  it('ни одна роль не удаляет записи', () => {
    // Не из недоверия: удалённая запись уезжает в корзину и продолжает занимать
    // своё место, а повторная перевозка из старой базы её не восстановит и
    // молча пропустит. Проверено на живой базе.
    for (const р of манифестПожСервиса.roles) {
      expect(р.canSoftDeleteAllObjectRecords).toBe(false);
      expect(р.canDestroyAllObjectRecords).toBe(false);
    }
  });

  it('ни одна роль не меняет настройки', () => {
    // Настройки — это и есть права. Роль, которой их дали, снимает с себя любой
    // запрет сама.
    for (const р of манифестПожСервиса.roles) {
      expect(р.canUpdateAllSettings).toBe(false);
    }
  });
});
