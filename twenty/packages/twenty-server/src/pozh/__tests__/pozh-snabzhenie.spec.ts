// пожсервис: замок на схему снабжения.
//
// ЗАЧЕМ ИМЕННО ЗДЕСЬ И ИМЕННО СЕЙЧАС. В Twenty **тип поля нельзя изменить после
// того, как в нём появилась первая запись** — это риск 4 карты работ. Пока CRM
// пустая, схему правят бесплатно; на следующий день после первой заявки любая
// ошибка в ней означает потерю данных. Значит, ошибки надо ловить сегодня, а не
// «когда дойдут руки до проверок».
//
// Проверки читают опись, а не работающую программу: они поймают ошибку в
// описании, но не поймают, если CRM опись не применила. Живая сверка глазами
// нужна отдельно и от этих проверок не отменяется.

import { FieldMetadataType } from 'twenty-shared/types';

import { ОБЪЕКТЫ } from 'src/pozh/manifest/pozh-ids';
import { манифестПожСервиса } from 'src/pozh/manifest/pozh-manifest';

const СНАБЖЕНИЕ = [
  ОБЪЕКТЫ.стройобъект,
  ОБЪЕКТЫ.позицияСпецификации,
  ОБЪЕКТЫ.заявка,
  ОБЪЕКТЫ.позицияЗаявки,
  ОБЪЕКТЫ.остаток,
  ОБЪЕКТЫ.движениеОстатка,
  ОБЪЕКТЫ.справка,
  ОБЪЕКТЫ.строкаСправки,
];

const объекты = манифестПожСервиса.objects;
const поля = манифестПожСервиса.fields ?? [];

const объектПо = (ид: string) =>
  объекты.find((о) => о.universalIdentifier === ид);

// Поля объекта — и свои, и добавленные общим списком в описи.
const поляОбъекта = (ид: string) => [
  ...(объектПо(ид)?.fields ?? []),
  ...поля.filter((п) => п.objectUniversalIdentifier === ид),
];

describe('снабжение: схема заведена целиком', () => {
  it('все восемь видов записей есть в описи', () => {
    for (const ид of СНАБЖЕНИЕ) {
      expect(объектПо(ид)).toBeDefined();
    }
  });

  // Объект, которого нет в меню, для человека не существует — правило заведено
  // после случая, когда четырнадцать объектов были в базе и ни одного в меню.
  it('каждый вид записей виден в меню', () => {
    const вМеню = new Set(
      (манифестПожСервиса.navigationMenuItems ?? []).map(
        (п) => п.targetObjectUniversalIdentifier,
      ),
    );

    for (const ид of СНАБЖЕНИЕ) {
      expect(вМеню.has(ид)).toBe(true);
    }
  });

  // Опознаватели вписаны руками, и повтор означал бы, что два объекта делят
  // одну таблицу. Twenty скажет об этом невнятно, а данные потеряются молча.
  it('опознаватели не повторяются ни у объектов, ни у полей', () => {
    const ид = объекты.map((о) => о.universalIdentifier);

    expect(new Set(ид).size).toBe(ид.length);

    const идПолей = объекты.flatMap((о) =>
      (о.fields ?? []).map((п) => п.universalIdentifier),
    );

    expect(new Set(идПолей).size).toBe(идПолей.length);
  });
});

describe('снабжение: количества целые, а не дробные', () => {
  // ЗАЧЕМ. Остаток складывается из десятков приходов и списаний. Дробное число
  // копит ошибку от строки к строке, и через месяц «числится 310» перестаёт
  // сходиться с суммой движений. Поэтому всё, что накапливается, лежит целым
  // числом тысячных долей единицы, и имя поля обязано об этом говорить.
  const количества = СНАБЖЕНИЕ.flatMap((ид) =>
    поляОбъекта(ид).filter(
      (п) => п.type === FieldMetadataType.NUMBER && /Qty|Milli/.test(п.name),
    ),
  );

  it('поля количеств заканчиваются на Milli — иначе единица непонятна', () => {
    expect(количества.length).toBeGreaterThan(0);

    for (const п of количества) {
      expect(п.name).toMatch(/Milli$/);
    }
  });

  it('у каждого количества в пояснении сказано, что это тысячные', () => {
    for (const п of количества) {
      expect(п.description ?? '').toMatch(/тысячн/i);
    }
  });
});

describe('снабжение: деньги не вводятся штатным экраном', () => {
  // ЗАЧЕМ. Риск 5 карты работ: штатный экран ввода сумм в Twenty теряет
  // копейки. Решение записано — суммы вводить только своей формой. Проверка
  // следит, чтобы про это не забыли при добавлении нового денежного поля.
  it('у каждого денежного поля сказано, что вводится своей формой', () => {
    const деньги = СНАБЖЕНИЕ.flatMap((ид) =>
      поляОбъекта(ид).filter((п) => п.type === FieldMetadataType.CURRENCY),
    );

    expect(деньги.length).toBeGreaterThan(0);

    for (const п of деньги) {
      expect(п.description ?? '').toMatch(/свое[йю] форм/i);
    }
  });
});

describe('снабжение: свободный остаток человек руками не правит', () => {
  // ЗАЧЕМ. Числится, зарезервировано и свободно — три числа, связанные
  // вычитанием. Если дать править третье, они разъедутся, и понять, какое
  // верное, будет нельзя.
  it('поле «свободно» закрыто от правки руками', () => {
    const свободно = поляОбъекта(ОБЪЕКТЫ.остаток).find(
      (п) => п.name === 'freeMilli',
    );

    expect(свободно).toBeDefined();
    expect(свободно?.isUIEditable).toBe(false);
  });
});

describe('снабжение: связи целы с обеих сторон', () => {
  // ЗАЧЕМ. У связи две половины. Если объявлена одна, Twenty при выкладке
  // ругается невнятно, а найти причину тяжело: ошибка говорит про поле, а
  // виновата пара.
  it('у каждой ссылки есть ответный список, и наоборот', () => {
    const все = [
      ...объекты.flatMap((о) => о.fields ?? []),
      ...поля,
    ].filter((п) => п.type === FieldMetadataType.RELATION);

    const поИд = new Map(все.map((п) => [п.universalIdentifier, п]));

    for (const п of все) {
      const ответная = поИд.get(
        п.relationTargetFieldMetadataUniversalIdentifier as string,
      );

      expect(ответная).toBeDefined();
      expect(ответная?.relationTargetFieldMetadataUniversalIdentifier).toBe(
        п.universalIdentifier,
      );
    }
  });
});

describe('снабжение: цепочка от заявки до списания не разорвана', () => {
  // ЗАЧЕМ. Это и есть та цепочка, которую владелец назвал главной мерой пилота:
  // «важно довести цепочку от заявки мастера до процентовки». Если хоть одно
  // звено не связано, довести её нельзя — и узнать об этом лучше сейчас.
  const ссылкаНа = (откуда: string, куда: string) =>
    поляОбъекта(откуда).some(
      (п) =>
        п.type === FieldMetadataType.RELATION &&
        п.relationTargetObjectMetadataUniversalIdentifier === куда,
    );

  it('заявка знает объект, а её позиции — заявку', () => {
    expect(ссылкаНа(ОБЪЕКТЫ.заявка, ОБЪЕКТЫ.стройобъект)).toBe(true);
    expect(ссылкаНа(ОБЪЕКТЫ.позицияЗаявки, ОБЪЕКТЫ.заявка)).toBe(true);
  });

  it('позиция заявки может лечь на спецификацию — по ней считают перебор', () => {
    expect(ссылкаНа(ОБЪЕКТЫ.позицияЗаявки, ОБЪЕКТЫ.позицияСпецификации)).toBe(true);
  });

  it('приход связывает движение с заявкой', () => {
    expect(ссылкаНа(ОБЪЕКТЫ.движениеОстатка, ОБЪЕКТЫ.заявка)).toBe(true);
    expect(ссылкаНа(ОБЪЕКТЫ.движениеОстатка, ОБЪЕКТЫ.остаток)).toBe(true);
  });

  it('списание связывает строку справки с остатком, а движение — со строкой', () => {
    expect(ссылкаНа(ОБЪЕКТЫ.строкаСправки, ОБЪЕКТЫ.справка)).toBe(true);
    expect(ссылкаНа(ОБЪЕКТЫ.строкаСправки, ОБЪЕКТЫ.остаток)).toBe(true);
    expect(ссылкаНа(ОБЪЕКТЫ.движениеОстатка, ОБЪЕКТЫ.строкаСправки)).toBe(true);
  });
});

describe('снабжение: списание не случается само', () => {
  // ЗАЧЕМ. Слова владельца дословно: «пока все они там нажимают кнопки, это всё
  // черновики. Как только я одобрю — списано». Признак утверждения и тот, кто
  // утвердил, — не украшение карточки, а единственное, что отличает
  // предложенное списание от случившегося.
  it('у движения есть признак утверждения и кто утвердил', () => {
    const имена = поляОбъекта(ОБЪЕКТЫ.движениеОстатка).map((п) => п.name);

    expect(имена).toContain('isApproved');
    expect(имена).toContain('approvedBy');
    expect(имена).toContain('approvedAt');
  });

  it('у справки тоже: без утверждения ни одна её строка не станет списанием', () => {
    const имена = поляОбъекта(ОБЪЕКТЫ.справка).map((п) => п.name);

    expect(имена).toContain('approvedBy');
    expect(имена).toContain('approvedAt');
  });
});

describe('снабжение: исходную просьбу прораба не затирают разбором', () => {
  // ЗАЧЕМ. Прораб пишет «просто кабель», снабженец расшифровывает. Если
  // затереть первое вторым, спор «я не это просил» решать будет нечем.
  it('у заявки и у её позиции сохраняется, как было написано', () => {
    expect(поляОбъекта(ОБЪЕКТЫ.заявка).map((п) => п.name)).toContain('rawText');
    expect(поляОбъекта(ОБЪЕКТЫ.позицияЗаявки).map((п) => п.name)).toContain('askedAs');
  });

  it('у строки справки сохраняется процент совпадения на момент решения', () => {
    const имена = поляОбъекта(ОБЪЕКТЫ.строкаСправки).map((п) => п.name);

    expect(имена).toContain('matchPercent');
    expect(имена).toContain('onHandAtMatchMilli');
  });
});
