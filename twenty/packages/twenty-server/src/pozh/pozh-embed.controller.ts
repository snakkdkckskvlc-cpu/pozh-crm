/**
 * пожсервис: выдача пропуска в службу документов.
 *
 * ЗАЧЕМ. Двадцать один наш экран (сверка таблиц, проверка счёта, реквизиты,
 * реестр на оплату, путевые листы и остальные) остаётся в службе на Python: их
 * не переписывают, Twenty показывает их в рамке. Но экран внутри рамки должен
 * понять, кто перед ним, а своей формы входа у службы больше нет.
 *
 * Здесь выписывается разовый пропуск: подписанный кусочек текста, в котором
 * только идентификаторы — кто и в каком пространстве. Служба проверяет подпись
 * сама, не спрашивая Twenty: иначе падение Twenty останавливало бы и разбор
 * файлов, который к нему отношения не имеет.
 *
 * ПОЧЕМУ РУЧКА ОТДАЁТ ГОТОВЫЙ АДРЕС, А НЕ ПРОПУСК. Чтобы собрать адрес,
 * достаточно склеить три строки — но тогда знание о том, где живёт служба и как
 * называется её путь, размазывается по внешней половине. Пусть об этом знает
 * одно место.
 *
 * СРОК ЖИЗНИ. Пять минут. Пропуск уходит в адрес рамки, а значит попадает в
 * журнал веб-сервера и в историю браузера — украденный оттуда через час уже не
 * годится. Служба сразу меняет его на обычную сессию.
 */

import { Controller, Get, Param, UseGuards } from '@nestjs/common';

import { createHmac } from 'node:crypto';

import { AuthUser } from 'src/engine/decorators/auth/auth-user.decorator';
import { AuthUserWorkspaceId } from 'src/engine/decorators/auth/auth-user-workspace-id.decorator';
import { AuthWorkspace } from 'src/engine/decorators/auth/auth-workspace.decorator';
import { JwtAuthGuard } from 'src/engine/guards/jwt-auth.guard';
import { NoPermissionGuard } from 'src/engine/guards/no-permission.guard';
import { WorkspaceAuthGuard } from 'src/engine/guards/workspace-auth.guard';
import { type UserEntity } from 'src/engine/core-modules/user/user.entity';
import { WorkspaceEntity } from 'src/engine/core-modules/workspace/workspace.entity';
import { RoleService } from 'src/engine/metadata-modules/role/role.service';
import { UserRoleService } from 'src/engine/metadata-modules/user-role/user-role.service';
import { КОД_ДОЛЖНОСТИ } from 'src/pozh/manifest/pozh-roli';

/**
 * АДРЕСА РУЧЕК ЛАТИНИЦЕЙ, хотя весь остальной код русский, и это не
 * непоследовательность.
 *
 * Сначала здесь было `@Get('screens')`. Ручка не работала НИ РАЗУ, и молча:
 * маршрут в списке значился, а запрос получал 404. Nest сверяет адрес до
 * раскодирования, а браузер кириллицу кодирует всегда — сравнивались
 * `/pozh/%D1%8D...` и `/pozh/экраны`. Незакодированный запрос отвергается ещё
 * раньше, с «400 Bad Request».
 *
 * Это третий случай одного и того же в проекте: имя параметра `пропуск`,
 * кириллический путь в клиенте на Python, теперь маршрут Nest. Правило:
 * **в адресе — латиница, русский только в том, что видит человек.**
 * (Служба на Python кириллицу в пути переносит — Starlette раскодирует до
 * сверки. Поэтому её адреса остались русскими: их видно в адресной строке.)
 */

/** Сколько живёт пропуск. Должно совпадать со службой документов. */
const СРОК_ГОДНОСТИ_СЕК = 300;

/**
 * Насколько запоминается список экранов. Меню строится при каждом открытии
 * страницы — без запоминания это был бы запрос к службе на каждый чих. Минута
 * выбрана так: новый экран появляется в меню почти сразу, а нагрузки нет.
 */
const ПАМЯТЬ_СПИСКА_МС = 60_000;

type Экран = { ключ: string; название: string; раздел: string };

type Раздел = {
  ключ: string;
  название: string;
  место: 'сверху' | 'снизу';
  экраны: Экран[];
};

type Список = { экраны: Экран[]; разделы: Раздел[] };

/**
 * Список экранов спрашивается у СЛУЖБЫ, а не хранится здесь копией.
 *
 * Копия здесь была, и я называл её «вторым независимым замком». Это было
 * преувеличение: файлы с диска отдаёт только служба, Twenty их вообще не видит,
 * и пропуск на экран не из её списка она отвергнет сама. То есть копия ничего не
 * охраняла — она только могла разойтись с оригиналом, и тогда в меню появлялся
 * бы пункт, который не открывается, или наоборот: экран есть, а попасть некуда.
 *
 * Настоящий замок остался там, где он что-то значит, — в службе. И с 03.09.2026
 * там же решается СОСТАВ меню: служба знает, какие экраны положены должности, и
 * отдаёт только их.
 *
 * ПАМЯТЬ РАЗДЕЛЕНА ПО ДОЛЖНОСТЯМ. Раньше здесь лежал один список на всех, и это
 * было верно, пока список был один. Теперь общая память показала бы бухгалтеру
 * то, что минуту назад запросил кадровик. Ключ — код должности: у двух
 * бухгалтеров меню одинаковое, и просить его дважды незачем.
 */
const память = new Map<string, { когда: number; список: Список }>();

const служба = (): string => process.env.POZH_DOCS_URL ?? 'http://localhost:8000';

const запроситьЭкраны = async (
  кодДолжности: string,
  пропуск: string,
): Promise<Список> => {
  const запомненное = память.get(кодДолжности);

  if (запомненное && Date.now() - запомненное.когда < ПАМЯТЬ_СПИСКА_МС) {
    return запомненное.список;
  }

  // Пропуск нужен и здесь: без него служба не знает, кто спрашивает, и отдаёт
  // самый узкий набор. Тот же подписанный пропуск, что и на открытие экрана, —
  // второго способа сказать «это наш человек» у нас нет и не должно быть.
  const адрес = `${служба()}/встроенный/список?pass=${encodeURIComponent(пропуск)}`;
  const ответ = await fetch(адрес);

  if (!ответ.ok) {
    throw new Error(`служба документов ответила ${ответ.status}`);
  }

  const тело = (await ответ.json()) as Список;

  память.set(кодДолжности, { когда: Date.now(), список: тело });

  return тело;
};

const б64 = (данные: Buffer | string): string =>
  Buffer.from(данные).toString('base64url').replace(/=+$/, '');

@Controller('pozh')
// Связка из трёх, как у остальных ручек Twenty. Одного WorkspaceAuthGuard мало,
// и это тоже не работало молча: он лишь СМОТРИТ, определено ли пространство, а
// определяет его JwtAuthGuard, читая токен. Без первого стража ручка отвечала
// «нет доступа» и вошедшему, и постороннему — одинаково.
@UseGuards(JwtAuthGuard, WorkspaceAuthGuard, NoPermissionGuard)
export class PozhEmbedController {
  constructor(
    private readonly userRoleService: UserRoleService,
    private readonly roleService: RoleService,
  ) {}

  /**
   * Код должности вошедшего — то, что уезжает в службу вместе с пропуском.
   *
   * ПОЧЕМУ КОД, А НЕ НАЗВАНИЕ. Пропуск уходит в адрес рамки, а значит попадает
   * в журнал веб-сервера и в историю браузера. Две латинские буквы там ничего
   * не рассказывают, слово «бухгалтер» — рассказывает.
   *
   * ПОЧЕМУ ПУСТАЯ СТРОКА, А НЕ ОШИБКА, если должность не назначена или роль
   * чужая (например, встроенный «Admin»). Служба на пустой код оставляет то,
   * что у неё записано, и в худшем случае человек видит общий набор экранов.
   * Уронить ему рабочий экран из-за ненастроенной должности — хуже.
   */
  private async кодДолжности(
    userWorkspaceId: string | undefined,
    workspaceId: string,
  ): Promise<string> {
    if (!userWorkspaceId) {
      return '';
    }

    try {
      const roleId = await this.userRoleService.getRoleIdForUserWorkspace({
        workspaceId,
        userWorkspaceId,
      });
      const роль = await this.roleService.getRoleById(roleId, workspaceId);

      return КОД_ДОЛЖНОСТИ[роль?.universalIdentifier ?? ''] ?? '';
    } catch {
      return '';
    }
  }

  /**
   * Подписанный разовый пропуск. Пустая строка — общий ключ не настроен.
   *
   * Собран отдельно, потому что нужен теперь дважды: на открытие экрана и на
   * запрос меню. Два места, склеивающие подпись каждое по-своему, разошлись бы
   * на первом же новом поле, а служба проверяет подпись над ТОЧНО ТЕМ ЖЕ
   * набором байтов — расхождение в один пробел означает «пропуск не подходит».
   */
  private выписатьПропуск(
    кто: string,
    пространство: string,
    кодДолжности: string,
  ): string {
    const ключ = process.env.POZH_GATE_KEY ?? '';

    if (!ключ) {
      return '';
    }

    const поля: Record<string, string | number> = {
      до: Math.floor(Date.now() / 1000) + СРОК_ГОДНОСТИ_СЕК,
      кто,
      пространство,
    };

    // Пустую должность не пишем вовсе: так пропуск байт в байт совпадает с тем,
    // что выписывала прежняя версия, и служба разбирает его как раньше.
    if (кодДолжности) {
      поля.роль = кодДолжности;
    }

    const тело = JSON.stringify(
      поля,
      // Порядок ключей и разделители обязаны совпадать со службой: она проверяет
      // подпись над ТОЧНО ТЕМ ЖЕ набором байтов. Пробел после запятой — уже
      // другая подпись. Порядок здесь не произвольный: он совпадает с русским
      // алфавитом, потому что служба складывает поля по алфавиту.
      ['до', 'кто', 'пространство', 'роль'],
    );

    const подпись = б64(createHmac('sha256', ключ).update(тело).digest());

    return `${б64(тело)}.${подпись}`;
  }

  @Get('screens')
  async список(
    @AuthUser() user: UserEntity,
    @AuthWorkspace() workspace: WorkspaceEntity,
    // allowUndefined, а не строгий режим: без него декоратор отвечает отказом,
    // когда запрос пришёл не от человека в браузере. Разделение по должностям
    // не повод ронять ручку — без опознавателя сотрудника мы просто не узнаем
    // должность и отдадим общий набор.
    @AuthUserWorkspaceId({ allowUndefined: true })
    userWorkspaceId: string | undefined,
  ) {
    const код = await this.кодДолжности(userWorkspaceId, workspace.id);
    const пропуск = this.выписатьПропуск(user.email, workspace.id, код);

    if (!пропуск) {
      return {
        экраны: [],
        разделы: [],
        ошибка:
          'Связь с проверкой документов не настроена. Скажите об этом ИТ-администратору: ' +
          'нужен общий ключ POZH_GATE_KEY.',
      };
    }

    try {
      // Разделы отдаются вместе с экранами: порядок и названия разделов
      // задаёт служба, а не меню. Иначе два места знают одно и то же и
      // расходятся, а какое из них главное — не понять.
      //
      // И состав меню тоже решает служба: там же стоит замок на самих экранах,
      // и меню обязано показывать ровно то, что откроется. Пункт, дающий отказ,
      // хуже отсутствующего — человек делает вывод про программу, а не про свою
      // должность.
      return await запроситьЭкраны(код, пропуск);
    } catch {
      // Пустое меню без объяснения выглядит как «функций больше нет». Служба
      // недоступна — значит экраны не открылись бы всё равно, и человеку надо
      // сказать об этом словами, а не молча спрятать половину программы.
      return {
        экраны: [],
        разделы: [],
        ошибка:
          'Служба проверки документов не отвечает. Скажите ИТ-администратору — ' +
          'разбор файлов сейчас недоступен.',
      };
    }
  }

  @Get('screen/:screen')
  async адресЭкрана(
    @Param('screen') screen: string,
    @AuthUser() user: UserEntity,
    @AuthWorkspace() workspace: WorkspaceEntity,
    // allowUndefined, а не строгий режим: без него декоратор отвечает отказом,
    // когда запрос пришёл не от человека в браузере. Разделение по должностям
    // не повод ронять ручку — без опознавателя сотрудника мы просто не узнаем
    // должность и отдадим общий набор.
    @AuthUserWorkspaceId({ allowUndefined: true })
    userWorkspaceId: string | undefined,
  ) {
    const код = await this.кодДолжности(userWorkspaceId, workspace.id);
    const пропуск = this.выписатьПропуск(user.email, workspace.id, код);

    if (!пропуск) {
      // Пустой ключ означает, что подпись сойдётся у кого угодно. Тихо выдать
      // пропуск в таком состоянии — худший исход, поэтому громкий отказ с
      // текстом, который можно показать человеку.
      return {
        ошибка:
          'Связь с проверкой документов не настроена. Скажите об этом ИТ-администратору: ' +
          'нужен общий ключ POZH_GATE_KEY.',
      };
    }

    let список: Список;

    try {
      список = await запроситьЭкраны(код, пропуск);
    } catch {
      return {
        ошибка: 'Служба проверки документов не отвечает. Попробуйте позже.',
      };
    }

    const найден = список.экраны.find((э) => э.ключ === screen);

    if (!найден) {
      // Список теперь отфильтрован под должность, поэтому сюда попадают два
      // разных случая: экрана нет вовсе и экран не для этого человека. Текст
      // общий намеренно — служба на открытии всё равно объяснит подробнее, а
      // здесь важнее не сказать лишнего про чужую работу.
      return { ошибка: `Экран «${screen}» вам не доступен.` };
    }

    return {
      экран: screen,
      название: найден.название,
      адрес: `${служба()}/встроенный/${screen}.html?pass=${encodeURIComponent(пропуск)}`,
      годен_секунд: СРОК_ГОДНОСТИ_СЕК,
    };
  }
}
