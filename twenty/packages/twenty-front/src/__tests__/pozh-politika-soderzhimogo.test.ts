// пожсервис: замок на вписанный руками адрес в политике содержимого.
//
// Политика содержимого — список мест, откуда браузеру разрешено что-либо
// брать. Наши экраны показываются в рамке со СТОРОННЕГО адреса (служба
// документов), и его надо там назвать.
//
// Сначала он был вписан прямо в разметку как localhost. На сервере компании
// адрес другой, и рамка оказалась бы ПУСТОЙ — причём молча: браузер просто не
// пускает чужой адрес, ошибки в журнале нет, человек видит белое поле.
//
// Теперь адрес подставляется при сборке из настройки. Проверка следит, чтобы
// его не вписали обратно: это правка на одну строчку, она выглядит безобидно, и
// заметить её потом невозможно.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const разметка = () =>
  readFileSync(join(__dirname, '..', '..', 'index.html'), 'utf-8');

const политика = (): string => {
  const найдено = разметка().match(
    /http-equiv="Content-Security-Policy"\s*\n?\s*content="([^"]*)"/,
  );

  if (найдено === null) {
    throw new Error('политика содержимого пропала из разметки');
  }

  return найдено[1];
};

describe('политика содержимого', () => {
  it('вообще есть', () => {
    // Без неё браузер тянет что угодно откуда угодно — а в системе документы
    // с обязательством о неразглашении.
    expect(политика().length).toBeGreaterThan(0);
  });

  it('не содержит вписанных руками адресов', () => {
    const вписанные = политика().match(/https?:\/\/[^\s;]+/g) ?? [];

    expect(вписанные).toEqual([]);
  });

  it('разрешает рамку со службы документов через настройку', () => {
    // Метка подставляется при сборке. Если её убрать, рамка перестанет
    // открываться вовсе — и тоже молча.
    expect(политика()).toContain('frame-src');
    expect(политика()).toContain('%POZH_DOCS_ORIGIN%');
  });

  it('запрещает показывать нас самих в чужой рамке', () => {
    // Иначе чужой сайт может показать нашу систему у себя и подсунуть человеку
    // свои кнопки поверх.
    expect(политика()).toContain("frame-ancestors 'none'");
  });
});
