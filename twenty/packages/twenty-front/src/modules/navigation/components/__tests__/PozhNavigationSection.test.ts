// пожсервис: замок на рукописный список объектов учёта в разделе меню.
//
// В `PozhNavigationSection` шесть объектов транспорта перечислены руками — их
// нельзя спросить у службы документов, потому что живут они в Twenty. Это
// слабое место: переименуют объект — пункт меню поведёт в никуда, и отказа
// никто не увидит, просто откроется пустая страница «не найдено».
//
// Поэтому проверка читает ОПИСАНИЕ ОБЪЕКТОВ С ДИСКА и сверяет с ним. Читать
// чужой пакет из проверки некрасиво, но это единственный способ поймать
// расхождение до того, как его увидит человек.

import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const ОПИСАНИЯ = join(
  __dirname,
  '../../../../../..',
  'twenty-server/src/pozh/manifest/objects',
);

const именаОбъектов = (): Set<string> => {
  const найденные = new Set<string>();

  for (const файл of readdirSync(ОПИСАНИЯ).filter((и) => и.endsWith('.ts'))) {
    const текст = readFileSync(join(ОПИСАНИЯ, файл), 'utf-8');

    for (const совпадение of текст.matchAll(/namePlural:\s*'([^']+)'/g)) {
      найденные.add(совпадение[1]);
    }
  }

  return найденные;
};

const изКомпонента = (): string[] => {
  const текст = readFileSync(join(__dirname, '..', 'PozhNavigationSection.tsx'), 'utf-8');
  const кусок = текст.slice(
    текст.indexOf('ОБЪЕКТЫ_УЧЁТА_В_РАЗДЕЛЕ'),
    текст.indexOf('const РазделМеню'),
  );

  return [...кусок.matchAll(/имя:\s*'([^']+)'/g)].map((с) => с[1]);
};

describe('объекты учёта в разделе меню', () => {
  it('описания объектов вообще нашлись', () => {
    // Без этого вся проверка молча проходила бы на пустом списке — та же
    // болезнь, от которой она заведена.
    expect(именаОбъектов().size).toBeGreaterThan(10);
    expect(изКомпонента().length).toBeGreaterThan(0);
  });

  it('каждый пункт ведёт в существующий объект', () => {
    const есть = именаОбъектов();
    const битые = изКомпонента().filter((имя) => !есть.has(имя));

    expect(битые).toEqual([]);
  });

  it('не дублируют раздел Twenty', () => {
    // Объект, оставшийся и там и тут, показывается в меню ДВАЖДЫ.
    const меню = readFileSync(
      join(__dirname, '../../../../../..', 'twenty-server/src/pozh/manifest/pozh-menyu.ts'),
      'utf-8',
    );
    // Ключи здесь русские, а `\w` кириллицу буквой не считает — с ним список
    // выходил пустым, и проверка проходила ВПУСТУЮ: я вернул рейсы в раздел
    // Twenty нарочно, и она этого не заметила. Поэтому берётся «всё до запятой»
    // и рядом стоит утверждение, что список не пуст.
    const вРазделеTwenty = [...меню.matchAll(/объект:\s*ОБЪЕКТЫ\.([^,\s]+)/g)].map(
      (с) => с[1],
    );

    expect(вРазделеTwenty.length).toBeGreaterThan(0);

    // Сопоставление «имя объекта в запросах» → «ключ в списке опознавателей».
    const ключи: Record<string, string> = {
      pozhWaybills: 'путевойЛист',
      pozhTrips: 'рейс',
      pozhVehicles: 'машина',
      pozhDrivers: 'водитель',
      pozhTrailers: 'прицеп',
      pozhPoints: 'точка',
    };

    const дважды = изКомпонента()
      .map((имя) => ключи[имя])
      .filter((ключ) => ключ !== undefined && вРазделеTwenty.includes(ключ));

    expect(дважды).toEqual([]);
  });
});
